# s22p02 에서 뗄 행 (프롭 앞머리로 찾는다)
DROP = ['미끄러져 내려와 더미가 되고', '셋에 자루를 하나씩 비운다']
PC_DROP = ['O1-25']


def close_brace(t, i):
    op = t[i]; cl = {'{': '}', '[': ']'}[op]
    d, q, j, esc = 0, None, i, False
    while j < len(t):
        c = t[j]
        if q:
            if esc: esc = False
            elif c == '\\': esc = True
            elif c == q: q = None
        elif c in '"\'`': q = c
        elif c == op: d += 1
        elif c == cl:
            d -= 1
            if d == 0: return j
        j += 1
    raise SystemExit('괄호 안 닫힘')


def q2(s):
    assert '"' not in s and '\\' not in s, s
    return '"%s"' % s


def drop_row(blk, needle):
    """프롭 앞머리로 행 하나를 통째로 뺀다. 앞의 쉼표까지 함께 지운다."""
    k = blk.index(needle)
    st = blk.rindex('[', 0, k)          # 행을 여는 대괄호
    en = close_brace(blk, st)           # 행을 닫는 대괄호
    pre = st
    while pre > 0 and blk[pre - 1] in ' \n': pre -= 1
    assert blk[pre - 1] == ',', repr(blk[pre - 8:pre + 2])
    return blk[:pre - 1] + blk[en + 1:]


def main():
    src = open(SK, encoding='utf-8').read()
    assert "{id:'s22p02b'" not in src, '이미 있다'
    assert os.path.exists(os.path.join(ROOT, 'img', 's22p02b.webp')), '그림이 없다'

    i = src.index("{id:'s22p02'")
    e = close_brace(src, i)
    blk = src[i:e + 1]

    for n in DROP:
        blk = drop_row(blk, n)
    for cid in PC_DROP:
        assert ',"%s"' % cid in blk, cid
        blk = blk.replace(',"%s"' % cid, '', 1)

    # 뗀 카드가 s22p02 에 하나도 안 남았는지
    moved = ['O1-23', 'O1-25', 'O1-25#1', 'O1-25#4', 'O1-25#5', 'O1-25#6', 'O1-24#1']
    for cid in moved:
        assert '"%s"' % cid not in blk, cid + ' 가 s22p02 에 남았다'

    src = src[:i] + blk + src[e + 1:]
    e = i + len(blk) - 1

    rows = []
    for prop, fact, cards in ROWS:
        r = '[' + q2(prop) + ',' + q2(fact)
        if cards: r += ',[' + ','.join(q2(c) for c in cards) + ']'
        rows.append(r + ']')

    panel = ("{id:'s22p02b',t:'자루를 실으면 물이 따라 든다',br:'" + BR + "',bx:`" + BX + "`,f:["
             + ',\n     '.join(rows) + ']}')
    out = src[:e + 1] + ',\n   ' + panel + src[e + 1:]

    ids = re.findall(r"\{id:'([sd]\d+p\d+[ab]?)'", out)
    assert len(ids) == len(set(ids)), '패널 id 중복'
    b2 = out[out.index("{id:'s22p02b'"):]
    b2 = b2[:close_brace(b2, 0) + 1]
    cards = re.findall(r'"([A-Z][A-Z0-9]*(?:-[A-Z0-9]+)*-[\w#]+)"', b2)
    assert len(cards) == len(set(cards)), '카드 중복: ' + str(cards)
    print('s22p02b 신설 · 행 %d · 카드 %d장 · s22p02 에서 행 2개 · pc 1개 뗌'
          % (len(ROWS), len(cards)))
    open(SK, 'w', encoding='utf-8').write(out)
    return 0


if __name__ == '__main__':
    sys.exit(main())
