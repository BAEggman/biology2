# -*- coding: utf-8 -*-
"""한 줄 보강 1차 — d03p04 열 머리 · s32p02 산화적 인산화 · s06p01 소품 이름"""
import sys, io
sys.path.insert(0, '/tmp/b2/tools')
import rowlib

P = '/tmp/b2/sketchy.html'
s = io.open(P, encoding='utf8').read()
before = s

# ── 1. d03p04 — SVG 에 이미 그려진 열 머리를 사실표로 내린다 ────────────
s = rowlib.append_row(s, 'd03p04',
  '★ 맨 윗줄 열 머리 셋 — <b>저장액(밖이 묽다)</b> · <b>등장액</b> · <b>고장액(밖이 진하다)</b>, '
  '그 바로 아래에 물의 방향이 「물이 세포 안으로 · 들고 나는 양이 같다 · 물이 세포 밖으로」로 적혀 있다',
  '이름은 언제나 <b>세포 밖</b>을 기준으로 부른다 — 밖이 묽으면 <b>저</b>장액, 밖이 진하면 <b>고</b>장액이다. '
  '물은 용질이 진한 쪽으로 가므로 저장액에선 <b>안으로</b>, 등장액에선 <b>순이동 없음</b>, 고장액에선 <b>밖으로</b> 간다',
  ['A1-144', 'A1-144#3', 'A1-63', 'A1-77', 'A1-78'])

# 같은 판 2번 행의 붙어버린 글 고침
s, ch, _ = rowlib.edit_row(s, 'd03p04', 2,
  fact='정상 — 동물에게 최적. <b>물의 순이동이 없다</b>는 것이 등장성의 뜻이다 — '
       '안팎의 용질 농도가 같으니 들어오는 만큼 나간다. 동물세포에게는 이 칸이 최적이다')
print('d03p04 2번 행 글 고침:', ch)

# ── 2. s32p02 — 판 전체가 곧 「산화적 인산화」다 ────────────────────────
s = rowlib.append_row(s, 's32p02',
  '★ 이 판 하나가 통째로 — 담장 끝에서 <b>짐이 손을 옮겨 가고</b>, 그 힘으로 담장 뒤에 물이 높이 차고, '
  '아치 하나로 쏟아진 물이 <b>물레방아</b>를 돌린다',
  '<b>산화적 인산화</b> — 짐을 넘기는 줄(<b>전자전달</b>)과 물레방아(<b>화학삼투</b>) 둘이 한 담장에서 이어진 것이다. '
  '세포호흡 4단계의 마지막이고, ATP의 <b>대부분</b>이 여기서 나온다. 기질수준 인산화와 갈리는 곳도 바로 이 둘의 있고 없음이다',
  ['B1-24', 'B1-25', 'B1-114', 'B1-204', 'B1-3#4'])

# ── 3. s06p01 — 그려져 있는데 사실표에 없던 소품에 이름을 붙인다 ─────────
#    ※ 다시마·켈프·김 은 그림에 없다 → 카드는 걸지 않는다 (그린 것만 건다)
s, ch, _ = rowlib.edit_row(s, 's06p01', 3,
  prop='가장 깊은 곳 + 빨간 튜브 + 처마에 걸린 <b>붉은 깃털 모양 해조</b>')
print('s06p01 3번 행 소품 이름:', ch)

io.open(P, 'w', encoding='utf8').write(s)
print('바뀐 글자수:', len(s) - len(before))
