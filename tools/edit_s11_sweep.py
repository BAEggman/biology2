     '그렇게 나온 조각이 <b>오카자키 절편</b>이다 — 지연가닥의 중간 산물은 긴 한 가닥이 '
     '아니라 <b>토막 여럿</b>이고, 선도가닥과 갈리는 자리가 정확히 이것이다",'
