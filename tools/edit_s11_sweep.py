def main():
    s = open(SK, encoding='utf-8').read()
    for old, new in EDITS:
        n = s.count(old)
        if n != 1:
            print('✗ 앵커가 %d회: %s…' % (n, old[:70]))
            return 1
        s = s.replace(old, new)
    for pid in ('s11p01', 's11p02'):
        i = s.index("{id:'%s'" % pid)
        d, q, k, esc = 0, None, i, False
        while k < len(s):
            c = s[k]
            if q:
                if esc: esc = False
                elif c == '\\': esc = True
                elif c == q: q = None
            elif c in '"\'`': q = c
            elif c == '{': d += 1
            elif c == '}':
                d -= 1
                if d == 0: break
            k += 1
        blk = s[i:k + 1]
        cards = re.findall(r'"([A-Z]\d?-[\w#]+)"', blk)
        assert len(cards) == len(set(cards)), '%s 카드 중복: %s' % (pid, cards)
        print('%s 카드 %d장' % (pid, len(cards)))
    open(SK, 'w', encoding='utf-8').write(s)
    print('그림 한 획 없이 여덟 장: E1-63#2·63#3·65#1·65#2·76·119#2·119#3·119#4')
    return 0


if __name__ == '__main__':
    sys.exit(main())
