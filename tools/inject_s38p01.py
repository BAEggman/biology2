def close_brace(t, i):
    op = t[i]
    cl = {'{': '}', '[': ']'}[op]
    d, q, j = 0, None, i
    while j < len(t):
        c = t[j]
        if q:
            if c == '\\':
                j += 2
                continue
            if c == q:
                q = None
        elif c in '"\'`':
            q = c
        elif c == op:
            d += 1
        elif c == cl:
            d -= 1
            if d == 0:
                return j
        j += 1
    raise SystemExit('괄호 안 닫힘')


def q2(s):
    assert '"' not in s and '\\' not in s, s
    return '"%s"' % s


def main():
    src = open(SK, encoding='utf-8').read()
    assert "{id:'s38'" not in src, '이미 있다'
    assert '`' not in BX and "'" not in BR and "'" not in SCENE_T

    i = src.index("{id:'s37'")
    e = close_brace(src, i)

    rows = []
    for prop, fact, cards in ROWS:
        r = '[' + q2(prop) + ',' + q2(fact)
        if cards:
            r += ',[' + ','.join(q2(c) for c in cards) + ']'
        rows.append(r + ']')

    panel = ("{id:'s38p01',t:'사다리 한 바퀴',br:'" + BR + "',bx:`" + BX
             + "`,f:[" + ',\n   '.join(rows) + ']}')
    scene = ("{id:'s38',t:'" + SCENE_T + "',gate:'" + GATE + "',unit:'" + UNIT
             + "',panels:[\n  " + panel + '\n ]}')
    out = src[:e + 1] + ',\n ' + scene + src[e + 1:]

    k = out.index("{id:'s38p01'")
    blk = out[k:close_brace(out, k) + 1]
    ids = re.findall(r"\{id:'([sd]\d+p\d+[ab]?)'", out)
    assert len(ids) == len(set(ids)), '패널 id 중복'
    sids = re.findall(r"\{id:'(s\d+)',t:", out)
    assert len(sids) == len(set(sids)), '장면 id 중복'
    assert sids.index('s38') == sids.index('s37') + 1, '장면 위치 오류'
    cards = re.findall(r'"([A-Z][\w-]*-[\w#]+)"', blk)
    assert len(cards) == len(set(cards)), '카드 중복: ' + str(cards)
    print('장면 %d개 · 패널 %d개 · s38p01 행 %d · 카드 %d장'
          % (len(sids), len(ids), len(ROWS), len(cards)))
    open(SK, 'w', encoding='utf-8').write(out)
    return 0


if __name__ == '__main__':
    sys.exit(main())
