    i = src.index("{id:'s10p01'")
    e = close_brace(src, i)

    rows = []
    for prop, fact, cards in ROWS:
        r = '[' + q2(prop) + ',' + q2(fact)
        if cards: r += ',[' + ','.join(q2(c) for c in cards) + ']'
        rows.append(r + ']')

    panel = ("{id:'s10p01b',t:'두 개찰구 — 훑는 쪽, 곧장 앉는 쪽',br:'" + BR
             + "',bx:`" + BX + "`,f:[" + ',\n     '.join(rows) + ']}')
    out = src[:e + 1] + ',\n   ' + panel + src[e + 1:]

    ids = re.findall(r"\{id:'([sd]\d+p\d+[ab]?)'", out)
    assert len(ids) == len(set(ids)), '패널 id 중복'
    blk = out[out.index("{id:'s10p01b'"):]
    blk = blk[:close_brace(blk, 0) + 1]
    cards = re.findall(r'"([A-Z][A-Z0-9]*(?:-[A-Z0-9]+)*-[\w#]+)"', blk)
    assert len(cards) == len(set(cards)), '카드 중복'
    print('s10p01b 신설 · 행 %d · 카드 %d장' % (len(ROWS), len(cards)))
    open(SK, 'w', encoding='utf-8').write(out)
    return 0


