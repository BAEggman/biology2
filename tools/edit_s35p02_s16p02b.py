def main():
    s = open(SK, encoding='utf-8').read()
    for old, new in EDITS:
        n = s.count(old)
        if n != 1:
            print('✗ 앵커가 %d회: %s…' % (n, old[:70]))
            return 1
        s = s.replace(old, new)
    for pid in ('s35p02', 's16p02b'):
        i = s.index("{id:'%s'" % pid)
        d, q, k, esc = 0, None, i, False
        while k < len(s):
            c = s[k]
            if q:
                if esc: esc = False
                elif c == '\\': esc = True
                elif c == q: q = None
            elif c in '"\'`': q = c
            elif c == '{': d += 1
            elif c == '}':
                d -= 1
                if d == 0: break
            k += 1
        blk = s[i:k + 1]
        cards = re.findall(r'"([A-Z]\d?-[\w#]+)"', blk)
        assert len(cards) == len(set(cards)), '%s 카드 중복' % pid
    open(SK, 'w', encoding='utf-8').write(s)
    print('s35p02 · s16p02b 사실표 정정 완료')
    return 0


if __name__ == '__main__':
    sys.exit(main())
