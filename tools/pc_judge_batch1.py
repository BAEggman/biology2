def add_row(pid, prop, fact, cards):
    """패널 f 배열 끝에 행 하나를 더한다."""
    SK = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                      'sketchy.html')
    s = open(SK, encoding='utf-8').read()
    i = s.index("{id:'%s'" % pid)
    fi = s.index('f:[', i)
    d, q, j, esc = 0, None, fi + 2, False
    while j < len(s):
        c = s[j]
        if q:
            if esc: esc = False
            elif c == '\\': esc = True
            elif c == q: q = None
        elif c in '"\'`': q = c
        elif c == '[': d += 1
        elif c == ']':
            d -= 1
            if d == 0: break
        j += 1
    for x in (prop, fact):
        assert '"' not in x and '\\' not in x, x
    row = ',\n     ["%s","%s",[%s]]' % (prop, fact, ','.join('"%s"' % c for c in cards))
    open(SK, 'w', encoding='utf-8').write(s[:j] + row + s[j:])
    print('  %-8s 행 추가 — %s' % (pid, prop[:30]))


