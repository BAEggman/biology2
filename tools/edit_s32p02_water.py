#!/usr/bin/env python3
"""s32p02 「담장 끝과 물레방아」 — 새 그림에 맞춰 사실표를 고치고 카드 다섯을 건다.

■ 왜 그림을 새로 그렸나 (픽셀 실측으로 결함 셋을 확인했다)
    짐    사실표는 「앞쪽 인부가 들었다」인데 그림에선 안 들고 있었다 (점검표 ② 유령)
    구슬  사실표는 「둘」인데 그림엔 하나였다                          (점검표 ⑤ 셈)
    물방울 이 그림의 물은 담장 뒤도 물레방아도 전부 H⁺인데 여기만 H₂O (점검표 ④ 한 상징 한 사실)

■ 새 그림 실측 (34edf1da / 2816×1536)
    편 손 위 물방울   정확히 둘 — 418화소 y=734 · 735화소 y=833 (세로로 나란히)
    구슬처럼 둥근 것  0개
    병               하나 · 코르크 마개 꽂힘
    담장 뒤 쌓인 물   y 197~690에 42,788화소
    짐               앞쪽 사람이 두 손으로 안고 있다 — 유령이 사라졌다

■ 고침
    물 = H⁺ 가 그림 전체에서 일관된다. 봉한 병만이 완성된 H₂O다.
    앞쪽에서 짐을 받아 든 사람이 곧 산소다 — 뒤로 넘길 사람이 없다.

■ 그린 것만 걸어 다섯 장 (전부 미연결이었다)
    B1-123 cyt a3이 전자를 넘기는 대상 = 산소   → #3 문간의 건네줌
    B1-124 최종 전자수용체 = 산소               → #4 짐을 받아 든 사람
    B1-21  마지막에서 전자가 반응하는 것        → #5 물 두 방울
    B1-22  마지막 반응의 생성물 = 물            → #5 봉한 병
    B1-125 산소가 양성자를 받아 만드는 것 = 물  → #5 봉한 병
"""
import os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SK = os.path.join(ROOT, 'sketchy.html')

OLD_BX = ('<p><b>구슬 둘과 물방울.</b> 마지막 펌프집에서 넘어온 짐이 작은 구슬 둘과 합쳐져 '
          '물방울이 된다. cyt a₃가 전자를 산소로 넘기고, 산소 원자가 전자와 H⁺ 둘을 받아 '
          '물이 되는 장면이다. 산소는 최종 전자수용체이지 CO₂를 만드는 데 쓰이는 것이 아니다. '
          '그래서 표지한 O₂를 마시게 하면 <b>물에서 가장 먼저</b> 나타난다.</p>')

NEW_BX = ('<p><b>물 두 방울과 봉한 병.</b> 담장 끝 문간에서 넘어온 짐을 앞쪽 사람이 '
          '<b>두 손으로 받아 든다</b>. 그 사람이 곧 <b>산소</b>다 — 뒤로 넘겨줄 사람이 없어서 '
          '최종 전자수용체다. 그 사람이 편 손 위에 <b>물 두 방울</b>이 떠 있고, 발 앞에는 '
          '<b>마개를 봉한 병</b>이 하나 놓였다. ★ <b>이 그림에서 흐르는 물은 전부 H⁺다</b> — '
          '담장 뒤에 쌓인 것도, 물레방아를 돌리고 나온 것도, 손 위의 두 방울도 모두 H⁺다. '
          '오직 <b>봉한 병만이 완성된 H₂O</b>이고, 봉했으니 더는 기울기에 끼지 않는다. '
          '산소는 최종 전자수용체이지 CO₂를 만드는 데 쓰이는 것이 아니다. '
          '그래서 표지한 O₂를 마시게 하면 <b>물에서 가장 먼저</b> 나타난다.</p>')

OLD_ROWS = ('["담장 끝 문간에서 짐을 넘겨받는 사람","복합체 IV(cyt a3)가 산소로 전자를 넘긴다"],\n'
            '  ["짐 + 작은 구슬 둘 → 물방울 하나",'
            '"최종 전자수용체 산소가 전자와 H+ 둘을 받아 물이 된다"]')

NEW_ROWS = (
    '["담장 끝 문간 — 안쪽 사람이 밖으로 나온 사람에게 짐을 건넨다",'
    '"복합체 IV(<b>cyt a₃</b>)가 전자를 <b>산소</b>로 넘긴다. 전자전달계에서 짐이 마지막으로 '
    '손을 바꾸는 자리다",["B1-123"]],\n'
    '  ["앞쪽에서 그 짐을 두 손으로 받아 든 사람 — 이 사람 뒤로는 넘겨줄 사람이 없다",'
    '"전자전달계의 <b>최종 전자수용체는 산소</b>다. 짐을 마지막으로 받아 드는 이 사람이 '
    '산소이고, 더 넘길 데가 없다는 것이 「최종」이다",["B1-124"]],\n'
    '  ["그 사람이 편 손 위에 뜬 <b>물 두 방울</b> → 발 앞에 놓인 <b>마개를 봉한 병 하나</b>",'
    '"산소가 전자와 함께 <b>H⁺ 둘</b>을 받아 <b>물</b>이 된다. ★ 이 그림에서 <b>흐르는 물은 '
    '전부 H⁺</b>다 — 담장 뒤에 쌓인 것도, 물레방아를 돌리고 나온 것도, 손 위의 두 방울도 '
    '모두 H⁺다. <b>봉한 병만이 완성된 H₂O</b>이고, 봉했으니 더는 기울기에 끼지 않는다",'
    '["B1-21","B1-22","B1-125"]]')


def main():
    s = open(SK, encoding='utf-8').read()
    for old, new, what in ((OLD_BX, NEW_BX, 'bx'), (OLD_ROWS, NEW_ROWS, '사실표')):
        n = s.count(old)
        if n != 1:
            print('✗ %s 앵커가 %d회: %s…' % (what, n, old[:70]))
            return 1
        s = s.replace(old, new)

    i = s.index("{id:'s32p02'")
    d, q, k, esc = 0, None, i, False
    while k < len(s):
        c = s[k]
        if q:
            if esc: esc = False
            elif c == '\\': esc = True
            elif c == q: q = None
        elif c in '"\'`': q = c
        elif c == '{': d += 1
        elif c == '}':
            d -= 1
            if d == 0: break
        k += 1
    blk = s[i:k + 1]
    cards = re.findall(r'"([A-Z]\d?-[\w#]+)"', blk)
    assert len(cards) == len(set(cards)), '카드 중복: %s' % cards
    rows = blk.count('],\n  [') + 1
    # 유령 방지 — 없앤 소품 낱말이 사실표에 남아 있으면 안 된다
    for ghost in ('구슬', '물방울'):
        assert ghost not in blk, '★ 지운 소품 「%s」가 아직 s32p02에 남아 있다' % ghost
    open(SK, 'w', encoding='utf-8').write(s)
    print('s32p02 사실표 %d행 · 카드 %d장 (새로 5장: B1-21·22·123·124·125)' % (rows, len(cards)))
    print('  ★ 「구슬」·「물방울」 낱말이 이 패널에서 완전히 사라졌다')
    return 0


if __name__ == '__main__':
    sys.exit(main())
