# -*- coding: utf-8 -*-
"""s12p03 재생성 반영 — 소화효소와 아미노산에 소리를 준다.
   사용자 지적:「여기도 트립신, 키모트립신, 라이신 아르기닌 등 phonetic 링크가
   전혀 없이 단순 그림 - 글자 암기야」"""
import sys, io
sys.path.insert(0,'/tmp/b2/tools'); import rowlib
P='/tmp/b2/sketchy.html'
s=io.open(P,encoding='utf8').read()

s,ch,_=rowlib.edit_row(s,'s12p03',0,
  prop='맨 위 줄 — <b>콜라 병</b>을 치켜든 인부가 <b>향이 피어오르는 마름모</b>의 <b>왼쪽</b>을 자른다',
  fact='<b>펩신</b> — 방향족 아미노산의 <b>N말단 쪽</b>(왼쪽). '
       '★ 콜라 병이 곧 이름이다 — <b>펩시</b>. 위에서 일하는 산성 효소라 탄산과도 어울린다. '
       '★ 마름모에서 피어오르는 것이 <b>향</b>이다 — <b>방향(芳香)</b>족 아미노산. 향이 안 나는 구슬은 방향족이 아니다')
print('#0 펩신 :', ch)

s,ch,_=rowlib.edit_row(s,'s12p03',1,
  prop='가운데 줄 — <b>드립 주전자</b>를 든 인부가 <b>쌀밥 공기</b>와 <b>R자 깃발</b>의 <b>오른쪽</b>을 자른다',
  fact='<b>트립신</b> — <b>Lys · Arg</b>의 <b>C말단 쪽</b>(오른쪽). '
       '★ 드립 주전자가 곧 이름이다 — 드립 ≈ <b>트립</b>신. '
       '★ 쌀밥이 <b>라이스</b> → <b>라이신</b>(Lys), R자 깃발이 <b>아르(R)</b> → <b>아르기닌</b>(Arg)이다. '
       '실제로 한 글자 약자도 Arg = R 이다. 둘 다 <b>양전하 염기성</b> 아미노산이라 한 짝으로 잘린다')
print('#1 트립신 :', ch)

s,ch,_=rowlib.edit_row(s,'s12p03',2,
  prop='아래 줄 — <b>기모노</b>를 입고 <b>드립 주전자</b>를 든 사람이 향이 피어오르는 마름모의 <b>오른쪽</b>을 자른다',
  fact='<b>키모트립신</b> — 방향족 아미노산의 <b>C말단 쪽</b>(오른쪽). '
       '★ <b>기모노 + 드립</b> 주전자가 곧 이름이다 — <b>키모</b>+<b>트립</b>신. '
       '주전자는 위 줄의 트립신과 <b>같은 것</b>이고 기모노만 하나 더 붙었다 — 이름이 겹치는 그대로다. '
       '★ 펩신과 자르는 자리가 <b>정반대</b>다 — 같은 마름모인데 펩신은 왼쪽, 키모트립신은 오른쪽이다')
print('#2 키모트립신 :', ch)

io.open(P,'w',encoding='utf8').write(s)
