MOVE = ['K2-18', 'K2-18#1', 'K2-18#2']


def close_brace(t, i):
    op = t[i]; cl = {'{': '}', '[': ']'}[op]
    d, q, j, esc = 0, None, i, False
    while j < len(t):
        c = t[j]
        if q:
            if esc: esc = False
            elif c == '\\': esc = True
            elif c == q: q = None
        elif c in '"\'`': q = c
        elif c == op: d += 1
        elif c == cl:
            d -= 1
            if d == 0: return j
        j += 1
    raise SystemExit('괄호 안 닫힘')


def q2(s):
    assert '"' not in s and '\\' not in s, s
    return '"%s"' % s


def main():
    src = open(SK, encoding='utf-8').read()
    assert "{id:'s21p02b'" not in src, '이미 있다'
    assert '`' not in BX.replace('`', '') or True
    assert os.path.exists(os.path.join(ROOT, 'img', 's21p02b.webp')), '그림이 없다'

    i = src.index("{id:'s21p02'")
    e = close_brace(src, i)
    blk = src[i:e + 1]

    # ① s21p02 의 pc 에서 외군 카드 셋을 뺀다 (s21p02b 가 행으로 접지한다)
    new = blk
    for cid in MOVE:
        assert '"%s"' % cid in new, cid + ' 가 s21p02 pc 에 없다'
        new = new.replace(',"%s"' % cid, '', 1)
    for cid in MOVE:
        assert '"%s"' % cid not in new, cid + ' 가 안 빠졌다'
    src = src[:i] + new + src[e + 1:]
    e = i + len(new) - 1

    rows = []
    for prop, fact, cards in ROWS:
        r = '[' + q2(prop) + ',' + q2(fact)
        if cards: r += ',[' + ','.join(q2(c) for c in cards) + ']'
        rows.append(r + ']')

    panel = ("{id:'s21p02b',t:'멀리 걸린 하나가 기준이다',br:'" + BR + "',bx:`" + BX + "`,f:["
             + ',\n     '.join(rows) + ']}')
    out = src[:e + 1] + ',\n   ' + panel + src[e + 1:]

    ids = re.findall(r"\{id:'([sd]\d+p\d+[ab]?)'", out)
    assert len(ids) == len(set(ids)), '패널 id 중복'
    b2 = out[out.index("{id:'s21p02b'"):]
    b2 = b2[:close_brace(b2, 0) + 1]
    cards = re.findall(r'"([A-Z][A-Z0-9]*(?:-[A-Z0-9]+)*-[\w#]+)"', b2)
    assert len(cards) == len(set(cards)), '카드 중복: ' + str(cards)
    print('s21p02b 신설 · 행 %d · 카드 %d장 (이동 %d · 신규 %d)'
          % (len(ROWS), len(cards), len(MOVE), len(cards) - len(MOVE)))
    open(SK, 'w', encoding='utf-8').write(out)
    return 0


if __name__ == '__main__':
    sys.exit(main())
