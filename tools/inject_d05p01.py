    assert svg.startswith('<svg') and svg.endswith('</svg>')

    # d03 장면 뒤에 새 장면을 붙인다 (도해는 끝에 모여 있다)
    i = src.index("{id:'d03',")
    e = close_brace(src, i)

    rows = []
    for prop, fact, cards in ROWS:
        r = '[' + q2(prop) + ',' + q2(fact)
        if cards:
            r += ',[' + ','.join(q2(c) for c in cards) + ']'
        rows.append(r + ']')

    panel = ("{id:'d05p01',t:'상인과 상반',svg:`" + svg + "`,br:'" + BR + "',bx:`" + BX
             + "`,f:[" + ',\n     '.join(rows) + ']}')
    scene = ("{id:'d05',t:'연관과 성유전 도해',gate:'E',"
             "unit:'같은 막대에 있는가 — 연관과 교차',panels:[\n   " + panel + ']}')
    out = src[:e + 1] + ',\n  ' + scene + src[e + 1:]

    k = out.index("{id:'d05p01'")
    blk = out[k:close_brace(out, k) + 1]
    ids = re.findall(r"\{id:'([sd]\d+p\d+[ab]?)'", out)
    assert len(ids) == len(set(ids)), '패널 id 중복'
    assert ids[-1] == 'd05p01', '위치 오류 — 맨 뒤여야 한다: ' + ids[-1]
    scenes = re.findall(r"\{id:'([sd]\d+)',t:", out)
    assert len(scenes) == len(set(scenes)), '장면 id 중복'
    cards = re.findall(r'"(E0-[\w#]+)"', blk)
    assert len(cards) == len(set(cards)), '카드 중복: ' + str(cards)
    print('패널 %d개 · d05p01 행 %d · 카드 %d장 · SVG %d바이트'
          % (len(ids), len(ROWS), len(cards), len(svg)))
    open(SK, 'w', encoding='utf-8').write(out)
    return 0


