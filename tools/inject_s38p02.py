    assert '`' not in BX and "'" not in BR

    i = src.index("{id:'s38p01'")
    e = close_brace(src, i)

    rows = []
    for prop, fact, cards in ROWS:
        r = '[' + q2(prop) + ',' + q2(fact)
        if cards:
            r += ',[' + ','.join(q2(c) for c in cards) + ']'
        rows.append(r + ']')

    panel = ("{id:'s38p02',t:'선반 위의 시험관 넷',br:'" + BR + "',bx:`" + BX
             + "`,f:[" + ',\n   '.join(rows) + ']}')
    out = src[:e + 1] + ',\n  ' + panel + src[e + 1:]

    k = out.index("{id:'s38p02'")
    blk = out[k:close_brace(out, k) + 1]
    ids = re.findall(r"\{id:'([sd]\d+p\d+[ab]?)'", out)
    assert len(ids) == len(set(ids)), '패널 id 중복'
    assert ids.index('s38p02') == ids.index('s38p01') + 1, '위치 오류'
    cards = re.findall(r'"([A-Z][\w-]*-[\w#]+)"', blk)
    assert len(cards) == len(set(cards)), '카드 중복: ' + str(cards)
    print('패널 %d개 · s38p02 행 %d · 카드 %d장' % (len(ids), len(ROWS), len(cards)))
    open(SK, 'w', encoding='utf-8').write(out)
