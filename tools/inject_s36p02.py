def close_brace(t, i):
    op = t[i]
    cl = {'{': '}', '[': ']'}[op]
    d, q, j = 0, None, i
    while j < len(t):
        c = t[j]
        if q:
            if c == '\\':
                j += 2
                continue
            if c == q:
                q = None
        elif c in '"\'`':
            q = c
        elif c == op:
            d += 1
        elif c == cl:
            d -= 1
            if d == 0:
                return j
        j += 1
    raise SystemExit('괄호 안 닫힘')


def q2(s):
    assert '"' not in s and '\\' not in s, s
    return '"%s"' % s


def main():
    src = open(SK, encoding='utf-8').read()
    assert "{id:'s36p02'" not in src, '이미 있다'
    assert '`' not in BX and "'" not in BR

    i = src.index("{id:'s36p01'")
    e = close_brace(src, i)

    rows = []
    for prop, fact, cards in ROWS:
        r = '[' + q2(prop) + ',' + q2(fact)
        if cards:
            r += ',[' + ','.join(q2(c) for c in cards) + ']'
        rows.append(r + ']')

    panel = ("{id:'s36p02',t:'한 바퀴 도는 마당',br:'" + BR + "',bx:`" + BX
             + "`,f:[" + ',\n   '.join(rows) + ']}')
    out = src[:e + 1] + ',\n  ' + panel + src[e + 1:]

    k = out.index("{id:'s36p02'")
    blk = out[k:close_brace(out, k) + 1]
    ids = re.findall(r"\{id:'([sd]\d+p\d+[ab]?)'", out)
    assert len(ids) == len(set(ids)), '패널 id 중복'
    assert ids.index('s36p02') == ids.index('s36p01') + 1, '위치 오류'
    cards = re.findall(r'"([A-Z][\w-]*-[\w#]+)"', blk)
    assert len(cards) == len(set(cards)), '카드 중복: ' + str(cards)
    print('패널 %d개 · s36p02 행 %d · 카드 %d장' % (len(ids), len(ROWS), len(cards)))
