# -*- coding: utf-8 -*-
"""s20p07 검수 고침 — 그림에 있는 것만 적는다 + ABA는 그린 판이 나른다.
   ① 3행 소품이 「어두운 방울이 드물다」라고 적었는데 그림의 왼쪽 방에는 어두운 방울이 넉넉하다.
      그림에 실제로 있는 것은 「틈으로 빨려 들어가는 어두운 방울」이다 — 그대로 고쳐 적는다.
   ② 4행 사실 칸이 ABA를 이름으로 부르는데 이 판에는 ABA를 나르는 소품이 없다.
      (셔터는 옆 판 s20p01b 것이다.) 이름을 지우고 옆 판을 가리킨다 — 대신 O1-22를 배열로 건다.
   ③ 「파란 렌즈」→「파란 유리알」 — 예약 심볼(포토트로핀)과 말을 맞춘다."""
import os
SK = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'sketchy.html')
s = open(SK, encoding='utf-8').read()
n0 = len(s)

SUBS = [
 # ③ br
 ('여는 신호는 <b>푸른 빛 · 시계 · 잎 속에 모자란 어두운 방울</b> 셋이고',
  '여는 신호는 <b>푸른 광선을 받는 파란 유리알 · 회중시계 · 틈으로 빨려 드는 어두운 방울</b> 셋이고'),
 # ① 3행 소품
 ('["★ 왼쪽에만 있는 것 셋 — 위에서 내려오는 <b>푸른 빛</b>과 그것을 받는 <b>파란 렌즈</b> · 벽에 걸린 <b>작은 시계</b> · 방 안에 <b>어두운 방울이 드물다</b>"',
  '["★ 왼쪽에만 있는 것 셋 — 위에서 쏟아지는 <b>푸른 광선</b>과 그것을 받는 <b>파란 유리알</b> 둘 · 옆에 걸린 <b>회중시계</b> · 벌어진 틈으로 <b>어두운 방울이 빨려 들어간다</b>"'),
 # ① 3행 사실
 ('<b>청색광</b>(아침 햇빛) · <b>생체시계</b>(신호 없이도 낮이면 연다) · <b>잎 속 CO₂가 낮을 때</b>(재료가 모자라니 연다)',
  '<b>청색광</b>(파란 유리알이 받는다) · <b>생체시계</b>(신호 없이도 낮이면 연다) · <b>잎 속 CO₂가 낮을 때</b>(빨아들이는 쪽이라는 것이 곧 모자라다는 뜻이다)'),
 # ② 4행 사실 — 이름을 지우고 그린 판을 가리킨다
 ('<b>닫는 신호는 하나</b> — <b>건조 스트레스</b>다. 마르면 <b>ABA</b>가 공변세포의 물을 빼내 쭈그러뜨린다. 셔터를 끌어내리는 그림은 옆 판(멈추게 하는 셋)에 있다',
  '<b>닫는 신호는 하나</b> — <b>건조 스트레스</b>다. 마르면 잎에서 나온 호르몬이 공변세포의 <b>물을 빼내</b> 쭈그러뜨린다. ★ 그 호르몬의 이름과 <b>셔터를 끌어내리는 그림</b>은 옆 판(멈추게 하는 셋)에 있다 — 이 판에는 그 소품이 없으므로 이름을 여기서 부르지 않는다'),
 # bx 도 같은 말을 쓴다 — 여기는 산문이라 감사 대상이 아니지만 말을 맞춘다
 ('(그래서 파란 렌즈가 달려 있다)', '(그래서 파란 유리알이 달려 있다)'),
]
for a, b in SUBS:
    assert s.count(a) == 1, '못 찾음(또는 여러 번): ' + a[:44]
    s = s.replace(a, b, 1)

open(SK, 'w', encoding='utf-8').write(s)
print('s20p07 글 고침 5곳 · %+d바이트' % (len(s) - n0))
