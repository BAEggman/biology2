PC = ['E1-87', 'E1-89']


def close_brace(t, i):
    op = t[i]
    cl = {'{': '}', '[': ']'}[op]
    d, q, j = 0, None, i
    while j < len(t):
        c = t[j]
        if q:
            if c == '\\':
                j += 2
                continue
            if c == q:
                q = None
        elif c in '"\'`':
            q = c
        elif c == op:
            d += 1
        elif c == cl:
            d -= 1
            if d == 0:
                return j
        j += 1
    raise SystemExit('괄호 안 닫힘')


def q2(s):
    assert '"' not in s and '\\' not in s, s
    return '"%s"' % s


def main():
    src = open(SK, encoding='utf-8').read()
    i = src.index("{id:'s11p03'")
    e = close_brace(src, i)
    old = src[i:e + 1]

    bx = old.split('bx:`', 1)[1]
    bx = bx[:bx.index('`')]
    for a, b in BX_FIX:
        n = bx.count(a)
        if n != 1:
            print('✗ bx 앵커 %d회: %s…' % (n, a[:60]))
            return 1
        bx = bx.replace(a, b)
    n = bx.count(BX_DROP)
    if n != 1:
        print('✗ 삭제 앵커 %d회' % n)
        return 1
    bx = bx.replace(BX_DROP, '')
    for ghost in ['그림에 대응 소품이 없다', '끌로 벽돌', '들고 나가는']:
        assert ghost not in bx, 'bx 에 옛 서술이 남았다: ' + ghost

    rows = []
    for prop, fact, cards in ROWS:
        r = '[' + q2(prop) + ',' + q2(fact)
        if cards:
            r += ',[' + ','.join(q2(c) for c in cards) + ']'
        rows.append(r + ']')

    assert "'" not in BR
    new = ("{id:'s11p03',pc:[" + ','.join(q2(c) for c in PC) + "],t:'수복 3종',br:'" + BR
           + "',bx:`" + bx + "`,f:[" + ',\n  '.join(rows) + ']}')
    out = src[:i] + new + src[e + 1:]

    k = out.index("{id:'s11p03'")
    blk = out[k:close_brace(out, k) + 1]
    head, body = blk.split(',f:[', 1)
    cards = re.findall(r'"([A-Z]\d?[\w]*-[\w#]+)"', head) + re.findall(r'"([A-Z]\d?[\w]*-[\w#]+)"', body)
    dup = [c for c in set(cards) if cards.count(c) > 1]
    assert not dup, '카드 중복: ' + str(dup)
    print('행 %d · 카드 %d장' % (len(ROWS), len(cards)))
    print('  ' + ' '.join(cards))
    open(SK, 'w', encoding='utf-8').write(out)
    print('블록 %d → %d bytes' % (len(old), len(new)))
    return 0


if __name__ == '__main__':
    sys.exit(main())
