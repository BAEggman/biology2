def close_brace(t, i):
    op = t[i]
    cl = {'{': '}', '[': ']'}[op]
    d, q, j = 0, None, i
    while j < len(t):
        c = t[j]
        if q:
            if c == '\\':
                j += 2
                continue
            if c == q:
                q = None
        elif c in '"\'`':
            q = c
        elif c == op:
            d += 1
        elif c == cl:
            d -= 1
            if d == 0:
                return j
        j += 1
    raise SystemExit('괄호 안 닫힘')


def q2(s):
    assert '"' not in s and '\\' not in s, s
    return '"%s"' % s


def main():
    src = open(SK, encoding='utf-8').read()
    assert "{id:'d05p07'" not in src, '이미 있다'
    assert '`' not in BX and "'" not in BR
    svg = open(SVGF, encoding='utf-8').read().strip()
    assert '`' not in svg and '\\' not in svg, 'SVG에 백틱·역슬래시'
    assert svg.startswith('<svg') and svg.endswith('</svg>')

    # ★ 그린 것만 건다 — 각 행이 대는 숫자가 그림 안에 실제로 있는지 확인한다
    bad = []
    for prop, _f, _c, needs in ROWS:
        for n in needs:
            if n not in svg:
                bad.append('%s ← 「%s」' % (prop[:26], n))
    if bad:
        print('✗ 그림에 없는 것을 걸려고 한다:')
        for b in bad:
            print('   ' + b)
        return 1

    i = src.index("{id:'d05p06'")
    e = close_brace(src, i)

    rows = []
    for prop, fact, cards, _n in ROWS:
        r = '[' + q2(prop) + ',' + q2(fact)
        if cards:
            r += ',[' + ','.join(q2(c) for c in cards) + ']'
        rows.append(r + ']')

    panel = ("{id:'d05p07',t:'검정교배 계산판',svg:`" + svg + "`,br:'" + BR + "',bx:`" + BX
             + "`,f:[" + ',\n     '.join(rows) + ']}')
    out = src[:e + 1] + ',\n   ' + panel + src[e + 1:]

    k = out.index("{id:'d05p07'")
    blk = out[k:close_brace(out, k) + 1]
    ids = re.findall(r"\{id:'([sd]\d+p\d+[ab]?)'", out)
    assert len(ids) == len(set(ids)), '패널 id 중복'
    assert ids.index('d05p07') == ids.index('d05p06') + 1, '위치 오류'
    cards = re.findall(r'"(E0-[\w#]+)"', blk)
    assert len(cards) == len(set(cards)), '카드 중복'
    allc = re.findall(r'"([A-Z]\d?-[\w#]+)"', out)
    print('패널 %d개 · d05p07 행 %d · 카드 %d장 · SVG %d바이트 · 문서 전체 링크 %d'
          % (len(ids), len(ROWS), len(cards), len(svg), len(allc)))
    open(SK, 'w', encoding='utf-8').write(out)
    return 0


if __name__ == '__main__':
    sys.exit(main())
