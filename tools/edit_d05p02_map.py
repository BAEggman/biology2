#!/usr/bin/env python3
"""d05p02 「거리와 재조합빈도」 — 그림에 이미 있는데 안 걸려 있던 카드 15장을 건다.

★ 그린 것만 건다 — 새로 그린 것은 하나도 없다. d05p02의 자(B띠)와 곡선(C띠)에
   이미 있는 것만 붙였다. d05p03에서 넷 건진 것과 같은 방법이다.

  #6  「18.5 % = 18.5 cM」(1 % = 1 cM)          → E0-164 · E0-165 · E0-138
  #10 「눈금을 빼면 거리가 나온다」(자에 일곱 자리)  → E0-150~157 여덟 장
  #11 「18.5 = 9.0 + 9.5」(인접 구간의 합)        → E0-158 · E0-159
  #13 「멀어질수록 관측이 자보다 작아진다(이중교차)」 → E0-160 · E0-163

  자에 찍힌 일곱 자리: 0 짧은 더듬이 · 16.5 고동색 눈 · 48.5 검은 몸 · 57.5 주홍색 눈 ·
  67.0 흔적 날개 · 75.5 아래로 휜 날개 · 104.5 갈색 눈.
  E0-150~157은 전부 이 자리들의 **차**를 묻는 것이라 자 하나로 다 나온다.

★ 걸지 않은 것 — E0-161(순서 결정에 여러 쌍 비교) · E0-162(가운데 유전자).
  세 유전자를 늘어놓고 견주는 그림이 d05p02에 없다. d05p07에서 그린다.
"""
import os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SK = os.path.join(ROOT, 'sketchy.html')

EDITS = [
    # #6 — 1 % = 1 cM. 거리를 구한 뒤 바로 이어지는 개념이 재조합빈도다
    ('"재조합빈도 <b>1 %가 지도거리 1 cM</b>이다. 빈도가 거리의 단위 그 자체다",["E0-14"]]',
     '"재조합빈도 <b>1 %가 지도거리 1 cM</b>이다. 빈도가 거리의 단위 그 자체다 — '
     '그래서 <b>9 cM은 재조합형 9 %</b>, <b>32 cM은 32 %</b>로 바로 읽는다. '
     '자에서 거리를 구했으면 다음에 할 말은 언제나 <b>재조합빈도</b>다",'
     '["E0-14","E0-164","E0-165","E0-138"]]'),

    # #10 — 자에서 빼면 나오는 것 전부
    ('["E0-54","E0-39","E0-40","E0-41","E0-42","E0-43","E0-44","E0-45","E0-46",'
     '"E0-49","E0-50","E0-51","E0-52","E0-53"]]',
     '["E0-54","E0-39","E0-40","E0-41","E0-42","E0-43","E0-44","E0-45","E0-46",'
     '"E0-49","E0-50","E0-51","E0-52","E0-53",'
     '"E0-150","E0-151","E0-152","E0-153","E0-154","E0-155","E0-156","E0-157"]]'),

    # #11 — 인접 구간의 합
    ('"<b>인접 구간의 합</b>으로도 멀리 떨어진 두 유전자 거리를 구할 수 있다. '
     '빼기와 더하기의 답이 같다",["E0-55","E0-70","E0-71","E0-72"]]',
     '"<b>인접 구간의 합</b>으로도 멀리 떨어진 두 유전자 거리를 구할 수 있다. '
     '빼기와 더하기의 답이 같다 — 9.0 + 9.5 = 18.5이고 32.0 + 9.0 = 41.0인 식이다",'
     '["E0-55","E0-70","E0-71","E0-72","E0-158","E0-159"]]'),

    # #13 — 이중교차 때문에 관측이 자보다 작아진다
    ('"재조합빈도가 <b>높으면 멀다</b>. 다만 멀어질수록 한 구간에서 교차가 두 번 일어나 '
     '겉으로는 부모형이 되고, 그만큼 관측값이 자보다 작아진다",["E0-10","E0-48"]]',
     '"재조합빈도가 <b>높으면 멀다</b>. 다만 멀어질수록 한 구간에서 <b>교차가 두 번</b> '
     '일어나 겉으로는 부모형이 되고, 그만큼 관측값이 자보다 작아진다. '
     '★ 그래서 인접 구간을 더한 값보다 <b>양 끝의 관측값이 더 작게</b> 나온다 — '
     '9 + 9.5 = 18.5인데 관측이 17 %인 것이 그 예다",'
     '["E0-10","E0-48","E0-160","E0-163"]]'),
]


def main():
    s = open(SK, encoding='utf-8').read()
    for old, new in EDITS:
        n = s.count(old)
        if n != 1:
            print('✗ 앵커가 %d회: %s…' % (n, old[:70]))
            return 1
        s = s.replace(old, new)
    i = s.index("{id:'d05p02'")
    d, q, k, esc = 0, None, i, False
    while k < len(s):
        c = s[k]
        if q:
            if esc: esc = False
            elif c == '\\': esc = True
            elif c == q: q = None
        elif c in '"\'`': q = c
        elif c == '{': d += 1
        elif c == '}':
            d -= 1
            if d == 0: break
        k += 1
    cards = re.findall(r'"(E0-[\w#]+)"', s[i:k + 1])
    assert len(cards) == len(set(cards)), '카드 중복'
    open(SK, 'w', encoding='utf-8').write(s)
    print('d05p02 카드 %d장 (새로 15장: E0-138·150~160·163·164·165)' % len(cards))
    return 0


if __name__ == '__main__':
    sys.exit(main())
