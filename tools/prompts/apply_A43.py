bad = 0; seen = {}
for lid, ops in E.items():
    p, d, ind, nl = load(lid)
    W, H = d['w'], d['h']
    for o in ops:
        if 'field' in o:
            v = d[o['field']]
            if v.count(o['old']) != 1: print(f'✕ {lid}.{o["field"]}: old {v.count(o["old"])}번'); bad += 1; continue
            d[o['field']] = v.replace(o['old'], o['new']); continue
        if 'new_after' in o:
            at = next((k for k, s in enumerate(d['stops']) if s['sid'] == o['new_after']), None)
            if at is None: print(f'✕ {lid}: {o["new_after"]} 없음'); bad += 1; continue
            mx = max(int(s['sid'][1:]) for s in d['stops'])
            st = {'sid': f's{mx + 1}'}; st.update(o['stop'])
            d['stops'].insert(at + 1, st); continue
        s = next((s for s in d['stops'] if s['sid'] == o['sid']), None)
        if s is None: print(f'✕ {lid}: {o["sid"]} 없음'); bad += 1; continue
        for f in ('obj', 'fact', 'hook', 'say'):
            if f in o:
                old, new = o[f]
                if s[f].count(old) != 1: print(f'✕ {lid} {o["sid"]}.{f}: old {s[f].count(old)}번 「{old[:30]}」'); bad += 1; continue
                s[f] = s[f].replace(old, new)
        if 'cards' in o:
            s['cards'] = list(s.get('cards') or []) + [c for c in o['cards'] if c not in (s.get('cards') or [])]
    # 검사
    for k, s in enumerate(d['stops']):
        if len(s['fact']) > 60: print(f'✕ {lid}#{k} {s["sid"]} 사실 {len(s["fact"])}자: {s["fact"]}'); bad += 1
        if len(s['say']) > 560: print(f'✕ {lid}#{k} {s["sid"]} 말 {len(s["say"])}자'); bad += 1
        b = s.get('box')
        if b:
            for x, y, w, h in (b if isinstance(b[0], list) else [b]):
                if not (x >= 0 and y >= 0 and w > 0 and h > 0 and x + w <= W and y + h <= H): print(f'✕ {lid}#{k} 상자 밖 {[x, y, w, h]}'); bad += 1
