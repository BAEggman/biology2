# ⚠ 세어야 하거나 방향이 뜻인 것(줄 셋 · 흰 꺾쇠 · 포도 줄 · 성냥/배턴과 화살 · 침에 섞인 것)은 여기 그리지 않는다 — PIL 로 얹는다.
