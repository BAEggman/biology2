#!/usr/bin/env python3
# L43c_sketch.py — L43c 「공장의 먼 응원단 — 인핸서 · 활성자 · DNA 굽힘 · 매개자 · 사일렌서」 바탕용 배치 밑그림
# 2048x1144 로 그려 1024x572 로 줄인다(Gemini 에 올리는 것은 sketch.png).
# 위 띠 = 벽돌 담장(뒤 담) / 왼쪽 · 가운데 = 켜진 유전자(응원 단 + 응원단원 셋 · 손잡은 양복 둘 · 타탄 깔개 + 일꾼 둘 + 인쇄 기계 + 종이띠 · 빨간 방석의 일꾼 · 왼쪽 뒤 절하는 집사)
# 오른쪽 뒤 = 꺼진 유전자(깔개 + 일꾼 둘 + 멈춘 인쇄 기계 · 빨간 사이렌 상자에 앉은 문지기) / 빈 응원 단 둘.
# ⚠ 금빛 짚끈(DNA) · 청록 / 회색 깔판 · 단 윗면의 빛깔 자리 · 사이렌 빛은 여기 그리지 않는다 — PIL(L43c_pil.py). 끈이 지날 바닥은 비워 둔다.
import math, sys
from PIL import Image, ImageDraw
OUT = sys.argv[1] if len(sys.argv) > 1 else '.'
W, H = 2048, 1144; S = 2
GROUND, BRICK, MORTAR = (240, 233, 205), (186, 84, 62), (120, 50, 40)
WOOD, SKIN, STEEL = (206, 160, 104), (250, 205, 170), (150, 160, 165)
im = Image.new('RGB', (W * S, H * S), GROUND); d = ImageDraw.Draw(im)
def sc(pts): return [(x * S, y * S) for x, y in pts]
def R(x0, y0, x1, y1, fill, outline=(0, 0, 0), w=4): d.rectangle([x0 * S, y0 * S, x1 * S, y1 * S], fill=fill, outline=outline, width=w * S if outline else 0)
def RR(x0, y0, x1, y1, r, fill, outline=(0, 0, 0), w=4): d.rounded_rectangle([x0 * S, y0 * S, x1 * S, y1 * S], radius=r * S, fill=fill, outline=outline, width=w * S if outline else 0)
def C(x, y, r, fill, outline=(0, 0, 0), w=4): d.ellipse([(x - r) * S, (y - r) * S, (x + r) * S, (y + r) * S], fill=fill, outline=outline, width=w * S if outline else 0)
def E(x, y, rx, ry, fill, outline=(0, 0, 0), w=4): d.ellipse([(x - rx) * S, (y - ry) * S, (x + rx) * S, (y + ry) * S], fill=fill, outline=outline, width=w * S if outline else 0)
def L(pts, fill=(0, 0, 0), w=6): d.line(sc(pts), fill=fill, width=w * S, joint='curve')
def P(pts, fill, outline=(0, 0, 0), w=4):
    d.polygon(sc(pts), fill=fill)
    if outline: d.line(sc(pts + [pts[0]]), fill=outline, width=w * S)
def man(x, y, body, h=180, head=SKIN, hat=None):
    """서 있는 사람(발이 (x, y))."""
    bw = h // 7; hr = h // 8
    R(x - bw, y - h * 0.80, x + bw, y - h * 0.36, body)
    L([(x - bw // 2, y - h * 0.36), (x - bw // 2 - 2, y)], w=9); L([(x + bw // 2, y - h * 0.36), (x + bw // 2 + 2, y)], w=9)
    C(x, y - h * 0.80 - hr + 3, hr, head)
    if hat: d.pieslice([(x - hr - 3) * S, (y - h * 0.80 - 2 * hr - 3) * S, (x + hr + 3) * S, (y - h * 0.80 + 3) * S], 180, 360, fill=hat, outline=(0, 0, 0), width=3 * S)
def sitter(x, y, body, hat, h=110):
    """바닥에 앉은 안전모 일꾼(엉덩이가 (x, y))."""
    R(x - 22, y - h * 0.62, x + 22, y - 8, body); L([(x - 16, y - 6), (x + 44, y)], w=10); L([(x + 10, y - 10), (x + 60, y - 4)], w=10)
    C(x, y - h * 0.62 - 20, 22, SKIN); d.pieslice([(x - 26) * S, (y - h * 0.62 - 48) * S, (x + 26) * S, (y - h * 0.62 - 2) * S], 180, 360, fill=hat, outline=(0, 0, 0), width=3 * S)
def press(x0, y0, x1, y1):
    """인쇄 기계 — 회청 몸통 · 굴대 셋 · 왼쪽 톱니."""
    RR(x0, y0 + 30, x1, y1, 14, (120, 150, 150), (0, 0, 0), 5)
    for k, col in enumerate(((235, 228, 205), (95, 110, 150), (190, 95, 85))):
        RR(x0 + 26, y0 + 44 + k * 48, x1 - 16, y0 + 84 + k * 48, 18, col, (0, 0, 0), 4)
    for cy in (y0 + 80, y0 + 170): C(x0 + 6, cy, 30, (130, 135, 140), (0, 0, 0), 4); C(x0 + 6, cy, 9, (70, 70, 75), None)
def tartan(pts):
    P(pts, (190, 60, 60))
    (x0, y0), (x1, y1), (x2, y2), (x3, y3) = pts
    for t in (0.2, 0.4, 0.6, 0.8):
        L([(x0 + (x1 - x0) * t, y0 + (y1 - y0) * t), (x3 + (x2 - x3) * t, y3 + (y2 - y3) * t)], (40, 110, 70), 6)
        L([(x0 + (x3 - x0) * t, y0 + (y3 - y0) * t), (x1 + (x2 - x1) * t, y1 + (y2 - y1) * t)], (50, 70, 150), 6)
def podium(cx, cy, w=260, hh=64):
    """낮은 나무 단 — 앞면 네모 + 윗면 평행사변형."""
    x0, x1 = cx - w // 2, cx + w // 2
    P([(x0, cy - hh // 2), (x1, cy - hh // 2), (x1 + 22, cy - hh // 2 - 20), (x0 + 22, cy - hh // 2 - 20)], (228, 190, 136))
    R(x0, cy - hh // 2, x1, cy + hh // 2, WOOD, (0, 0, 0), 4)

# ── 뒤 담(벽돌)
R(0, 0, W, 170, BRICK, None)
for r in range(6):
    y = 8 + r * 27; L([(0, y + 27), (W, y + 27)], MORTAR, 3)
    for x in range(-60 + (r % 2) * 60, W, 120): L([(x, y), (x, y + 27)], MORTAR, 3)
L([(0, 170), (W, 170)], (0, 0, 0), 6)

# ── 왼쪽 뒤: 허리 굽혀 절하는 키 큰 집사(검은 연미복 · 흰 장갑) — 두 손을 앞 아래로 모아 내밀었다(끈의 꺾인 자리를 쥘 손)
L([(190, 300), (186, 470)], (20, 20, 24), 16); L([(222, 300), (226, 470)], (20, 20, 24), 16)                    # 다리
E(206, 478, 40, 10, (20, 20, 24))                                                                                # 구두
P([(170, 262), (390, 270), (396, 326), (176, 330)], (28, 28, 34))                                                # 수평으로 굽힌 윗몸
P([(176, 300), (150, 400), (196, 392), (210, 322)], (28, 28, 34))                                                # 연미복 꼬리
C(428, 322, 30, SKIN); L([(404, 300), (452, 296)], (40, 40, 40), 8)                                              # 숙인 머리
L([(350, 320), (392, 400), (420, 426)], (28, 28, 34), 14); C(424, 430, 13, (250, 250, 250), (0, 0, 0), 3)        # 팔 + 흰 장갑 손
L([(376, 322), (416, 396), (446, 420)], (28, 28, 34), 14); C(450, 424, 13, (250, 250, 250), (0, 0, 0), 3)

# ── 먼 고리 도중의 빈 응원 단(작게)
podium(150, 762, 150, 50)

# ── 깔개 왼쪽 코앞: 응원 단 + 폼폼 든 응원단원 셋(빨강 · 노랑 · 파랑)
podium(500, 912, 264, 66)
for k, (x, col) in enumerate(((426, (225, 60, 55)), (506, (245, 205, 60)), (586, (70, 120, 220)))):
    man(x, 872, (250, 250, 250), 178)
    P([(x - 26, 872 - 178 * 0.40), (x + 26, 872 - 178 * 0.40), (x + 38, 872 - 178 * 0.22), (x - 38, 872 - 178 * 0.22)], col)   # 치마
    if k < 2:
        L([(x - 20, 742), (x - 42, 678)], (0, 0, 0), 7); L([(x + 20, 742), (x + 42, 678)], (0, 0, 0), 7)
        C(x - 46, 664, 24, col); C(x + 46, 664, 24, col)
    else:
        L([(x - 20, 742), (x - 42, 678)], (0, 0, 0), 7); C(x - 46, 664, 24, col)
        L([(x + 20, 748), (x + 76, 790)], (0, 0, 0), 7); C(x + 20, 800, 20, col)                                # 오른손은 양복에게 내밀고 폼폼 하나는 허리에

# ── 손에 손잡은 회색 양복 둘(매개자)
man(735, 952, (150, 152, 160), 188); man(822, 956, (150, 152, 160), 188)
L([(712, 826), (668, 792)], (0, 0, 0), 7)                                                                        # 왼쪽 양복의 왼손 ↔ 응원단원의 손
L([(756, 832), (800, 836)], (0, 0, 0), 7)                                                                        # 둘이 맞잡은 손
L([(846, 836), (900, 880)], (0, 0, 0), 7)                                                                        # 오른쪽 양복의 오른손 ↔ 일꾼의 손

# ── 켜진 유전자: 타탄 깔개 + 안전모 일꾼 둘 + 인쇄 기계 + 해 도안 종이띠
tartan([(880, 1034), (1296, 1034), (1356, 872), (940, 872)])
press(1112, 690, 1304, 932)
P([(1150, 930), (1272, 930), (1408, 1144), (1250, 1144)], (252, 248, 232))                                       # 종이띠
C(1296, 1046, 26, (250, 200, 50)); [L([(1296 + 34 * math.cos(a), 1046 + 34 * math.sin(a)), (1296 + 46 * math.cos(a), 1046 + 46 * math.sin(a))], (240, 170, 40), 5) for a in [k * math.pi / 4 for k in range(8)]]
sitter(930, 1004, (70, 110, 180), (245, 200, 50)); L([(912, 944), (900, 884)], (0, 0, 0), 7)                     # 왼쪽 일꾼은 한 손을 들어 양복의 손을 잡았다
sitter(1030, 1018, (70, 110, 180), (245, 200, 50))

# ── 깔개 바로 뒤: 빨간 방석 + 주황 안전모 일꾼(근거리 조절 요소)
E(1040, 832, 56, 18, (215, 60, 60)); sitter(1036, 826, (90, 150, 100), (240, 140, 50), 100)

# ── 인쇄 기계 너머: (깔판 셋은 PIL) 가운데 깔판 자리에 놓일 빈 응원 단
podium(1592, 800, 136, 46)

# ── 오른쪽 뒤: 꺼진 유전자 — 같은 깔개 · 같은 일꾼 둘 · 종이 없는 인쇄 기계
tartan([(1496, 524), (1808, 524), (1848, 410), (1536, 410)])
press(1654, 236, 1836, 470)
sitter(1556, 498, (70, 110, 180), (245, 200, 50), 100); sitter(1620, 510, (70, 110, 180), (245, 200, 50), 100)

# ── 가운데 뒤: 빨간 사이렌 상자에 올라앉은 회색 제복 문지기(팔짱)
R(950, 330, 1090, 404, (205, 55, 50), (0, 0, 0), 4)
d.pieslice([1036 * S, 286 * S, 1084 * S, 334 * S], 180, 360, fill=(240, 80, 70), outline=(0, 0, 0), width=3 * S); R(1032, 310, 1088, 330, (90, 90, 96), (0, 0, 0), 3)
R(966, 240, 1012, 332, (125, 130, 140)); C(989, 216, 24, SKIN); R(962, 190, 1016, 204, (90, 95, 105), (0, 0, 0), 3)       # 문지기(챙 모자)
L([(966, 276), (1012, 290)], (0, 0, 0), 8); L([(1012, 276), (966, 290)], (0, 0, 0), 8)                           # 팔짱
L([(972, 332), (958, 372)], (60, 62, 70), 12); L([(1006, 332), (1020, 372)], (60, 62, 70), 12)                   # 늘어뜨린 다리

im = im.resize((W, H), Image.LANCZOS); im.save(f'{OUT}/sketch_full.png'); im.resize((1024, 572), Image.LANCZOS).save(f'{OUT}/sketch.png')
print('ok', f'{OUT}/sketch.png')
