#!/usr/bin/env python3
# L10c_sketch.py — L10c 「조차장의 오타 열차 — 점 돌연변이 다섯 · 돌연변이원」 바탕용 배치 밑그림
# 2048x1144 로 그려 1024x572 로 줄인다(Gemini 에 올리는 것은 sketch.png).
# 위 띠 = 원본 사다리(DNA)와 돌연변이원 셋 + 자는 수리공 / 가운데 = 빈 선로 여섯(열차 · 구슬 사슬 · 동그라미는 PIL) / 왼쪽 = 손댄 이들 / 오른쪽 = 결과 · 에임스.
# ⚠ 열차 · 구슬 사슬 · 나무판 · 빨간 동그라미 · 사다리 칸 빛깔 · 내려오는 화살은 여기 그리지 않는다 — PIL(L10c_trains.py).
import math, sys
from PIL import Image, ImageDraw
OUT = sys.argv[1] if len(sys.argv) > 1 else '.'
W, H = 2048, 1144; S = 2
SKY, GROUND = (249, 248, 225), (234, 234, 195)
RAIL, WOOD, SKIN = (140, 142, 146), (200, 150, 90), (250, 205, 170)
im = Image.new('RGB', (W * S, H * S), SKY); d = ImageDraw.Draw(im)
def sc(pts): return [(x * S, y * S) for x, y in pts]
def R(x0, y0, x1, y1, fill, outline=(0, 0, 0), w=4): d.rectangle([x0 * S, y0 * S, x1 * S, y1 * S], fill=fill, outline=outline, width=w * S if outline else 0)
def RR(x0, y0, x1, y1, r, fill, outline=(0, 0, 0), w=4): d.rounded_rectangle([x0 * S, y0 * S, x1 * S, y1 * S], radius=r * S, fill=fill, outline=outline, width=w * S if outline else 0)
def C(x, y, r, fill, outline=(0, 0, 0), w=4): d.ellipse([(x - r) * S, (y - r) * S, (x + r) * S, (y + r) * S], fill=fill, outline=outline, width=w * S if outline else 0)
def E(x, y, rx, ry, fill, outline=(0, 0, 0), w=4): d.ellipse([(x - rx) * S, (y - ry) * S, (x + rx) * S, (y + ry) * S], fill=fill, outline=outline, width=w * S if outline else 0)
def L(pts, fill=(0, 0, 0), w=6): d.line(sc(pts), fill=fill, width=w * S, joint='curve')
def P(pts, fill, outline=(0, 0, 0), w=4):
    d.polygon(sc(pts), fill=fill)
    if outline: d.line(sc(pts + [pts[0]]), fill=outline, width=w * S)
def man(x, y, body, head=SKIN, h=150):
    bw = max(14, h // 6); hr = max(16, h // 6)
    R(x - bw, y - h, x + bw, y - h * 0.3, body); L([(x - bw // 2, y - h * 0.3), (x - bw // 2 - 3, y)], w=8); L([(x + bw // 2, y - h * 0.3), (x + bw // 2 + 3, y)], w=8)
    C(x, y - h - hr + 4, hr, head)

# ── 땅
P([(0, 300), (600, 280), (1300, 296), (W, 282), (W, H), (0, H)], GROUND, None)
# ── 위 띠: 받침 둘 위에 가로누운 나무 사다리(원본 = DNA) — 칸 빛깔은 PIL
for tx in (520, 1240):                                                              # 받침(작업 발판 꼴)
    L([(tx - 50, 345), (tx, 214), (tx + 50, 345)], (150, 105, 60), 10); L([(tx - 30, 300), (tx + 30, 300)], (150, 105, 60), 6)
for y in (150, 210): R(330, y, 1400, y + 12, WOOD, (0, 0, 0), 3)                     # 두 기둥(오른쪽은 부러져 끊김)
for k in range(17): R(360 + k * 62, 162, 372 + k * 62, 210, (120, 190, 110) if k % 2 == 0 else (220, 90, 80), (0, 0, 0), 2)
P([(1420, 140), (1520, 170), (1516, 184), (1418, 154)], WOOD); P([(1420, 204), (1516, 250), (1510, 262), (1416, 216)], WOOD)   # 부러져 처진 끝 토막
# 해 + 굵은 햇살 → 녹아 붙은 두 칸과 그을음
C(130, 120, 70, (250, 200, 50)); [L([(130 + 86 * math.cos(a), 120 + 86 * math.sin(a)), (130 + 118 * math.cos(a), 120 + 118 * math.sin(a))], (240, 170, 40), 8) for a in [k * math.pi / 6 for k in range(12)]]
P([(196, 146), (430, 150), (440, 196), (190, 172)], (255, 225, 120), None)
E(452, 186, 34, 26, (190, 120, 70)); C(452, 182, 12, (30, 30, 30), None)
# 사다리 위의 작은 검은 게 + 기울인 갈색 약병 + 방울
E(820, 128, 44, 24, (40, 40, 45)); [L([(790 + k * 20, 146), (784 + k * 22, 162)], (40, 40, 45), 5) for k in range(4)]; C(772, 104, 12, (40, 40, 45), None); C(866, 100, 12, (40, 40, 45), None)
P([(880, 60), (940, 84), (926, 118), (866, 96)], (150, 95, 50)); C(944, 132, 7, (150, 200, 90), (0, 0, 0), 2)
# 손뼈가 비치는 기계 + 번개 줄기 → 부러진 사다리
RR(1600, 60, 1840, 300, 20, (170, 176, 186), (0, 0, 0), 5); C(1720, 160, 70, (40, 60, 70)); [L([(1700 + k * 14, 200), (1696 + k * 16, 130)], (240, 240, 240), 6) for k in range(4)]
for wx in (1640, 1800): C(wx, 316, 20, (70, 70, 76))
L([(1600, 180), (1540, 150), (1560, 200), (1480, 176), (1500, 216), (1424, 190)], (255, 220, 60), 10)
# 받침에 기대어 자는 수리공(연장통은 닫힘 · 쇠망치는 바닥에)
C(600, 262, 26, SKIN); P([(574, 286), (640, 286), (700, 344), (560, 344)], (70, 130, 190)); L([(640, 344), (720, 344)], (60, 60, 70), 12)
R(730, 316, 800, 346, (200, 60, 50), (0, 0, 0), 3); L([(820, 344), (870, 344)], (120, 120, 125), 8)
# ── 가운데: 나란한 빈 선로 여섯(겹줄 · 침목 없음 · 오른쪽 끝 차막이) — 열차는 PIL 이 얹는다
for y in (476, 592, 708, 824, 940, 1056):
    for dy in (0, 12): R(280, y + dy, 1010, y + dy + 6, RAIL, (0, 0, 0), 2)
    R(1010, y - 20, 1024, y + 26, (190, 60, 50), (0, 0, 0), 3)
# ── 선로 왼쪽: 손댄 이들
man(120, 560, (60, 70, 110), h=150); P([(176, 390), (204, 390), (204, 556), (190, 590), (176, 556)], (220, 50, 50))          # 검수원 + 사람 키만 한 빨간 색연필
man(110, 800, (70, 110, 180), h=150); L([(132, 706), (196, 690)], (0, 0, 0), 7); R(192, 676, 220, 702, (60, 120, 220), (0, 0, 0), 2); R(34, 756, 78, 800, (200, 200, 205), (0, 0, 0), 3)   # 칠장이 + 붓 + 페인트 통
man(110, 960, (230, 170, 60), h=120); L([(134, 880), (184, 850)], (150, 105, 60), 8); R(174, 816, 220, 854, WOOD, (0, 0, 0), 3)      # 나무망치 든 일꾼
man(170, 1110, (60, 60, 60), h=110); R(92, 1014, 140, 1062, (220, 60, 50), (0, 0, 0), 4)                                             # 창 하나를 끼고 달아나는 도둑(줄무늬 · 눈가리개)
# ── 선로 오른쪽: 그래서 어떻게 됐나
man(1150, 640, (250, 250, 250), h=180); L([(1116, 506), (1076, 470)], (0, 0, 0), 6); L([(1184, 506), (1224, 470)], (0, 0, 0), 6)     # 무언극 배우(어깨 으쓱)
P([(1070, 690), (1150, 668), (1226, 700), (1266, 778), (1226, 806), (1196, 742), (1146, 714), (1084, 722)], (215, 50, 50))           # 길쭉하게 휘어 찌그러진 붉은 원반(얼굴 · 팔다리)
# ── 오른쪽: 에임스 — 약병 물총을 겨눈 실험복 + 이젤의 둥근 배지 둘
man(1440, 1090, (252, 252, 252), h=240); L([(1470, 900), (1560, 880)], (0, 0, 0), 9); R(1552, 858, 1636, 892, (90, 170, 220), (0, 0, 0), 3); R(1572, 814, 1606, 860, (150, 95, 50), (0, 0, 0), 3)
for ex, n in ((1760, 40), (1946, 3)):
    L([(ex - 60, 1096), (ex, 640), (ex + 60, 1096)], (150, 105, 60), 8); C(ex, 800, 88, (235, 220, 170), (0, 0, 0), 5); C(ex, 800, 76, (245, 235, 200), (0, 0, 0), 2)
    for k in range(n):
        a = k * 2.4; r = 8 + (k * 37 % 62); C(ex + r * math.cos(a), 800 + r * math.sin(a), 5, (250, 250, 245), (0, 0, 0), 1)
L([(1636, 874), (1680, 846)], (150, 200, 90), 4)
im = im.resize((W, H), Image.LANCZOS); im.save(f'{OUT}/sketch_2048.png')
im.resize((1024, 572), Image.LANCZOS).save(f'{OUT}/sketch.png')
print('ok')
