#!/usr/bin/env python3
# L43d_sketch.py — L43d 「같은 끈, 다른 공장」 바탕용 배치 밑그림
# 2048x1144 로 그려 1024x572 로 줄인다(Gemini 에 올리는 것은 sketch.png).
# Gemini 가 그릴 것만 그린다: 벽돌 담 띠 둘 · 붉은 벽돌집(간) · 큰 눈알(수정체) · 응원단 두 조(초록 둘 · 보라 둘 — 맨바닥에 세운다. 단은 PIL)
#   · 오른쪽 길가 세 묶음(위 = 갈색 달걀 + 노른자 + 튕겨 나오는 초록 응원단원 + 양 / 가운데 = 배에서 나온 줄기 아기 + 어른 옷 속 줄기 아기와 금빛 응원단원 넷 / 아래 = 갈라 연 뼈 속 줄기 아주머니 + 붉은 원반 + 흰 옷 경비)
# ⚠ 두 마당의 가구(끈 · 타탄 깔개 넷 · 팻말 넷 · 응원 단 둘 · 인쇄 기계 · 종이띠)와 화살은 여기 그리지 않는다 — PIL(L43d_pil.py)이 한 벌을 두 번 찍는다. 마당 바닥은 비워 둔다.
import math, sys
from PIL import Image, ImageDraw
OUT = sys.argv[1] if len(sys.argv) > 1 else '.'
W, H = 2048, 1144; S = 2
GROUND, BRICK, MORTAR = (240, 233, 205), (186, 84, 62), (120, 50, 40)
SKIN = (250, 205, 170)
GRN, PUR, GOLD = (70, 170, 90), (150, 92, 200), (245, 195, 50)
im = Image.new('RGB', (W * S, H * S), GROUND); d = ImageDraw.Draw(im)
def sc(pts): return [(x * S, y * S) for x, y in pts]
def R(x0, y0, x1, y1, fill, outline=(0, 0, 0), w=4): d.rectangle([x0 * S, y0 * S, x1 * S, y1 * S], fill=fill, outline=outline, width=w * S if outline else 0)
def RR(x0, y0, x1, y1, r, fill, outline=(0, 0, 0), w=4): d.rounded_rectangle([x0 * S, y0 * S, x1 * S, y1 * S], radius=r * S, fill=fill, outline=outline, width=w * S if outline else 0)
def C(x, y, r, fill, outline=(0, 0, 0), w=4): d.ellipse([(x - r) * S, (y - r) * S, (x + r) * S, (y + r) * S], fill=fill, outline=outline, width=w * S if outline else 0)
def E(x, y, rx, ry, fill, outline=(0, 0, 0), w=4): d.ellipse([(x - rx) * S, (y - ry) * S, (x + rx) * S, (y + ry) * S], fill=fill, outline=outline, width=w * S if outline else 0)
def L(pts, fill=(0, 0, 0), w=6): d.line(sc(pts), fill=fill, width=w * S, joint='curve')
def P(pts, fill, outline=(0, 0, 0), w=4):
    d.polygon(sc(pts), fill=fill)
    if outline: d.line(sc(pts + [pts[0]]), fill=outline, width=w * S)
def cheer(x, y, col, h=180, up=True):
    """폼폼 든 응원단원(발이 (x, y)) — 흰 윗옷 · col 치마 · col 폼폼."""
    bw = h // 7; hr = h // 8
    R(x - bw, y - h * 0.80, x + bw, y - h * 0.40, (250, 250, 250))
    P([(x - bw, y - h * 0.42), (x + bw, y - h * 0.42), (x + bw + 12, y - h * 0.24), (x - bw - 12, y - h * 0.24)], col)
    L([(x - bw // 2, y - h * 0.24), (x - bw // 2 - 2, y)], w=8); L([(x + bw // 2, y - h * 0.24), (x + bw // 2 + 2, y)], w=8)
    C(x, y - h * 0.80 - hr + 3, hr, SKIN)
    if up:
        L([(x - bw, y - h * 0.74), (x - bw - 20, y - h * 1.04)], w=6); L([(x + bw, y - h * 0.74), (x + bw + 20, y - h * 1.04)], w=6)
        C(x - bw - 22, y - h * 1.10, h // 8, col); C(x + bw + 22, y - h * 1.10, h // 8, col)
    else:
        C(x - bw - 8, y - h * 0.50, h // 9, col); C(x + bw + 8, y - h * 0.50, h // 9, col)
def sprout(x, y):
    """머리 위의 초록 줄기(두 잎)."""
    L([(x, y), (x, y - 26)], (40, 130, 60), 5); E(x - 14, y - 32, 14, 7, (70, 180, 80), (0, 0, 0), 2); E(x + 14, y - 34, 14, 7, (70, 180, 80), (0, 0, 0), 2)
def wall(y0, y1, x1=1410):
    R(0, y0, x1, y1, BRICK, None)
    n = (y1 - y0) // 30
    for r in range(n):
        y = y0 + r * 30; L([(0, y + 30), (x1, y + 30)], MORTAR, 3)
        for x in range(-60 + (r % 2) * 60, x1, 120): L([(x, y), (x, y + 30)], MORTAR, 3)
    L([(0, y1), (x1, y1)], (0, 0, 0), 6); L([(x1, y0), (x1, y1)], (0, 0, 0), 6)
    if y0 > 0: L([(0, y0), (x1, y0)], (0, 0, 0), 6)

# ── 담 띠 둘(마당마다 뒤 담)
wall(0, 90); wall(530, 620)

# ── 위 마당 왼쪽 끝: 붉은 벽돌집(간)
R(22, 272, 138, 416, BRICK, (0, 0, 0), 4)
for y in (300, 328, 356, 384): L([(22, y), (138, y)], MORTAR, 2)
P([(6, 278), (80, 190), (154, 278)], (74, 84, 100)); R(64, 352, 98, 416, (120, 80, 50), (0, 0, 0), 3); R(104, 300, 126, 324, (200, 225, 240), (0, 0, 0), 2)

# ── 위 마당 왼쪽: 초록 응원단 둘(맨바닥 — 단은 PIL 이 발밑에 그린다)
cheer(238, 350, GRN); cheer(306, 350, GRN)

# ── 아래 마당 왼쪽 끝: 받침 위의 큰 눈알(수정체 세포)
P([(52, 884), (108, 884), (122, 948), (38, 948)], (150, 155, 165)); C(80, 822, 64, (252, 252, 252)); C(100, 822, 30, (70, 130, 220)); C(104, 822, 14, (20, 20, 24), None); C(112, 812, 5, (255, 255, 255), None)

# ── 아래 마당 오른쪽: 보라 응원단 둘
cheer(1282, 880, PUR); cheer(1350, 880, PUR)

# ── 오른쪽 길가 위: 갈색 달걀(구멍 · 금) + 떠낸 노른자 + 튕겨 나오는 초록 응원단원 + 걸어 나오는 양
E(1600, 300, 150, 102, (215, 172, 122)); E(1566, 214, 46, 16, (60, 42, 30))
L([(1720, 250), (1740, 280), (1722, 304), (1746, 334), (1728, 360)], (0, 0, 0), 4)
C(1470, 424, 28, (250, 190, 40))
# 튕겨 나오는 응원단원(비스듬히 날아간다)
C(1764, 84, 20, SKIN); L([(1756, 100), (1722, 150)], (250, 250, 250), 26); P([(1708, 140), (1742, 162), (1716, 190), (1688, 166)], GRN)
L([(1700, 178), (1672, 214)], w=6); L([(1716, 184), (1700, 226)], w=6); C(1806, 60, 20, GRN); C(1716, 78, 20, GRN)
for k in range(3): L([(1596 + k * 22, 196 - k * 6), (1650 + k * 24, 150 - k * 10)], (120, 120, 120), 3)
# 양
E(1900, 330, 90, 62, (250, 250, 248)); [C(1820 + k * 30, 276 + (k % 2) * 8, 20, (250, 250, 248), (0, 0, 0), 3) for k in range(6)]
E(1994, 300, 28, 24, (236, 220, 210)); [L([(x, 380), (x, 428)], (60, 50, 50), 8) for x in (1850, 1885, 1930, 1962)]

# ── 오른쪽 길가 가운데: 큰 배(梨)에서 나온 줄기 아기 / 헐렁한 어른 옷 속 줄기 아기 + 금빛 응원단원 넷
E(1522, 694, 74, 90, (205, 208, 92)); E(1522, 616, 48, 50, (205, 208, 92)); E(1522, 584, 36, 12, (90, 90, 40))
C(1522, 546, 30, SKIN); sprout(1522, 518); L([(1500, 566), (1474, 528)], w=7); L([(1544, 566), (1570, 528)], w=7)
# 어른 옷(셔츠 · 넥타이 · 큰 구두)에 파묻힌 아기
P([(1778, 668), (1882, 668), (1894, 770), (1766, 770)], (120, 150, 205)); P([(1823, 668), (1837, 668), (1843, 728), (1830, 744), (1817, 728)], (200, 60, 60))
L([(1780, 676), (1764, 748)], (120, 150, 205), 20); L([(1880, 676), (1896, 748)], (120, 150, 205), 20)
E(1802, 784, 34, 12, (30, 30, 34)); E(1862, 784, 34, 12, (30, 30, 34))
C(1830, 640, 32, SKIN); sprout(1830, 610)
for x in (1668, 1726, 1934, 1992): cheer(x, 792, GOLD, 140, up=False)

# ── 오른쪽 길가 아래: 길게 갈라 연 큰 뼈 속의 줄기 아주머니 + 뼈 밖의 붉은 원반 · 흰 옷 경비
for cx, cy in ((1470, 922), (1470, 1050), (1812, 922), (1812, 1050)): C(cx, cy, 42, (238, 226, 196))
RR(1460, 912, 1822, 1060, 50, (238, 226, 196)); RR(1506, 934, 1782, 1040, 36, (200, 62, 56))
R(1574, 1004, 1610, 1030, (150, 100, 60), (0, 0, 0), 3)                                    # 걸상
E(1592, 986, 36, 34, (150, 195, 235)); C(1592, 938, 26, SKIN); sprout(1592, 914)
E(1902, 1046, 38, 30, (205, 50, 45)); E(1902, 1046, 16, 12, (238, 150, 150), None)
R(1966, 962, 2006, 1040, (248, 248, 248)); L([(1976, 1040), (1974, 1100)], w=9); L([(1996, 1040), (1998, 1100)], w=9); C(1986, 938, 22, SKIN); R(1962, 908, 2010, 922, (250, 250, 250), (0, 0, 0), 3)

im = im.resize((W, H), Image.LANCZOS); im.save(f'{OUT}/sketch_full.png'); im.resize((1024, 572), Image.LANCZOS).save(f'{OUT}/sketch.png')
print('ok', f'{OUT}/sketch.png')
