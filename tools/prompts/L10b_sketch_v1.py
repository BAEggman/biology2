#!/usr/bin/env python3
# L10b_sketch.py — L10b 「레일의 세 칸 객차 — 코돈 · 개시와 종결 · tRNA 의 모양 · 사슬의 행선지」 바탕용 배치 밑그림
# 2048x1144 로 그려 1024x572 로 줄인다(Gemini 에 올리는 것은 sketch.png).
# 세 띠: 가운데 = 레일 위 객차 일곱 + 보라 정거장 / 앞마당 왼쪽 = 도색장 / 앞마당 오른쪽 = 사슬의 행선지.
# ⚠ 세어야 하는 것 · 빛깔이 뜻인 것(창의 빛깔 · 체스판 64칸 · 갈고리 둘 + 사다리 · 말풍선 · 이정표 구슬 · 나무판의 네모)은 여기 그리지 않는다 — PIL 로 얹는다.
import sys
from PIL import Image, ImageDraw
OUT = sys.argv[1] if len(sys.argv) > 1 else '.'
W, H = 2048, 1144; S = 2
SKY, GROUND = (249, 248, 225), (234, 234, 195)
PUR, PURL, RAIL = (160, 95, 204), (222, 191, 240), (140, 142, 146)
CAR, GLASS, WOOD = (176, 192, 208), (236, 240, 244), (200, 150, 90)
SKIN = (250, 205, 170)
im = Image.new('RGB', (W * S, H * S), SKY); d = ImageDraw.Draw(im)
def sc(pts): return [(x * S, y * S) for x, y in pts]
def R(x0, y0, x1, y1, fill, outline=(0, 0, 0), w=4): d.rectangle([x0 * S, y0 * S, x1 * S, y1 * S], fill=fill, outline=outline, width=w * S if outline else 0)
def RR(x0, y0, x1, y1, r, fill, outline=(0, 0, 0), w=4): d.rounded_rectangle([x0 * S, y0 * S, x1 * S, y1 * S], radius=r * S, fill=fill, outline=outline, width=w * S if outline else 0)
def C(x, y, r, fill, outline=(0, 0, 0), w=4): d.ellipse([(x - r) * S, (y - r) * S, (x + r) * S, (y + r) * S], fill=fill, outline=outline, width=w * S if outline else 0)
def E(x, y, rx, ry, fill, outline=(0, 0, 0), w=4): d.ellipse([(x - rx) * S, (y - ry) * S, (x + rx) * S, (y + ry) * S], fill=fill, outline=outline, width=w * S if outline else 0)
def L(pts, fill=(0, 0, 0), w=6): d.line(sc(pts), fill=fill, width=w * S, joint='curve')
def P(pts, fill, outline=(0, 0, 0), w=4):
    d.polygon(sc(pts), fill=fill)
    if outline: d.line(sc(pts + [pts[0]]), fill=outline, width=w * S)
def man(x, y, body, head=SKIN, h=150):
    """서 있는 사람 자리표(발이 y)."""
    bw = max(14, h // 6); hr = max(16, h // 6)
    R(x - bw, y - h, x + bw, y - h * 0.3, body); L([(x - bw // 2, y - h * 0.3), (x - bw // 2 - 3, y)], w=8); L([(x + bw // 2, y - h * 0.3), (x + bw // 2 + 3, y)], w=8)
    C(x, y - h - hr + 4, hr, head)
def car(x, y=560):
    """창 셋 달린 객차 — 몸통 x..x+200 · 지붕 y · 바퀴는 레일(700)에."""
    RR(x, y, x + 200, y + 116, 14, CAR, (0, 0, 0), 5); R(x - 6, y - 8, x + 206, y + 6, (120, 136, 156), (0, 0, 0), 4)
    for k in range(3): R(x + 22 + k * 56, y + 26, x + 66 + k * 56, y + 72, GLASS, (0, 0, 0), 4)
    for cx in (x + 46, x + 154): C(cx, y + 124, 20, (70, 70, 76), (0, 0, 0), 4); C(cx, y + 124, 7, (190, 190, 195), None)
def plank(x0, y0, x1, y1): R(x0, y0, x1, y1, WOOD, (0, 0, 0), 4); L([(x0 + 12, y0 + 10), (x0 + 16, y1 - 10)], (150, 105, 60), 3); L([(x1 - 16, y0 + 12), (x1 - 12, y1 - 8)], (150, 105, 60), 3)

# ── 땅(멀리 완만한 언덕 선)
P([(0, 470), (500, 440), (1100, 462), (1600, 436), (W, 456), (W, H), (0, H)], GROUND, None)
# ── 레일(겹줄 · 침목 없음) + 왼쪽 끝 겨자색 중산모 + 오른쪽 끝 차막이
for y in (700, 720): R(0, y, 1990, y + 10, RAIL, (0, 0, 0), 3)
E(78, 690, 58, 14, (205, 160, 60)); RR(40, 640, 116, 694, 26, (205, 160, 60), (0, 0, 0), 4); R(42, 676, 114, 688, (140, 100, 40), None)
R(1984, 640, 2008, 736, (190, 60, 50), (0, 0, 0), 4); R(1960, 652, 2030, 676, (240, 240, 240), (0, 0, 0), 4)
# ── 객차 일곱
XS = [150, 380, 720, 1070, 1300, 1525, 1750]
for x in XS: car(x)
# ① 맨 앞 객차 지붕의 황제(월계관 · 흰 토가 · 붉은 띠 · 오른쪽으로 뻗은 팔)
man(246, 552, (250, 250, 250), h=150); L([(226, 404), (246, 396), (266, 404)], (70, 150, 60), 8)
L([(266, 430), (350, 400)], (0, 0, 0), 9); L([(226, 420), (268, 500)], (200, 50, 50), 10)
# ② 보라 정거장: 객차를 품은 문틀(작은 상자) + 위의 큰 돔(앞을 갈라 속이 보임)
R(676, 524, 708, 740, PUR); R(932, 524, 964, 740, PUR); R(676, 506, 964, 544, PUR)
P([(600, 520), (600, 330), (640, 190), (720, 115), (820, 92), (920, 115), (1000, 190), (1040, 330), (1040, 520)], PUR)
P([(630, 506), (630, 336), (664, 214), (734, 146), (820, 126), (906, 146), (976, 214), (1010, 336), (1010, 506)], PURL)
R(644, 446, 770, 506, (190, 150, 225))                                   # 좌석(긴 걸상)
# 할아버지: 허리를 세우고 두 다리를 앞으로 뻗어 앉음(L 자) · 한 팔은 머리 위로 · 다른 손에 종이(클로버)
R(706, 300, 758, 446, (120, 150, 200)); R(706, 420, 930, 458, (110, 110, 130)); R(916, 400, 948, 458, (90, 70, 60))      # 몸통 · 뻗은 다리 · 발
C(732, 258, 40, SKIN); P([(704, 272), (760, 272), (750, 340), (714, 340)], (250, 250, 250), (0, 0, 0), 3)                  # 얼굴 · 흰 수염
L([(736, 306), (748, 160)], (120, 150, 200), 18); C(749, 152, 11, SKIN, (0, 0, 0), 3)                                      # 번쩍 든 팔
L([(752, 330), (824, 330)], (120, 150, 200), 16); R(820, 286, 900, 376, (255, 255, 255), (0, 0, 0), 3)                     # 앞으로 내민 팔 + 종이
for (ax, ay) in [(848, 318), (872, 318), (860, 338)]: C(ax, ay, 12, (70, 170, 80), (0, 0, 0), 2)                            # 세 잎
L([(860, 348), (860, 366)], (40, 120, 50), 4)
# 발끝에서 늘어진 금빛 열쇠(이빨 셋이 아래 객차의 창 셋으로)
L([(932, 458), (932, 500), (910, 548)], (90, 70, 40), 3); C(910, 556, 13, (240, 195, 60), (0, 0, 0), 3); L([(900, 560), (744, 560)], (240, 195, 60), 9)
for tx in (764, 820, 876): L([(tx, 560), (tx, 588)], (240, 195, 60), 9)
# ③ 차막이 앞 세 객차 지붕 — 나무판 든 셋
man(1380, 552, (250, 170, 200), h=140); P([(1344, 470), (1416, 470), (1436, 500), (1324, 500)], (255, 200, 225), (0, 0, 0), 3); plank(1418, 380, 1478, 480)   # 발레리나(튀튀) + 나무판
man(1600, 552, (90, 160, 120), h=140); plank(1632, 420, 1692, 520); [L([(1586 + k * 9, 392), (1582 + k * 10, 366)], (60, 40, 30), 4) for k in range(4)]            # 비명 지르는 사람(곤두선 머리) + 껴안은 나무판
man(1850, 552, (230, 160, 60), h=140); plank(1808, 330, 1892, 386); [C(1838 + k * 12, 470 + (k % 2) * 16, 5, (90, 60, 30), None) for k in range(3)]               # 원시인(표범 무늬) + 번쩍 든 나무판
# ── 앞마당 왼쪽: 도색장 — 이젤의 체스판 · 칠장이 · 받침대의 객차 · 페인트 통 넷
L([(70, 1100), (190, 770)], (150, 105, 60), 10); L([(330, 1100), (210, 770)], (150, 105, 60), 10); L([(200, 780), (200, 1110)], (150, 105, 60), 8)
R(58, 782, 342, 1066, (245, 235, 205), (0, 0, 0), 5)
for i in range(8):
    for j in range(8):
        if (i + j) % 2: R(62 + i * 35, 786 + j * 35, 62 + (i + 1) * 35, 786 + (j + 1) * 35, (170, 130, 90), None)
man(408, 1090, (70, 110, 180), h=170); L([(430, 960), (490, 934)], (0, 0, 0), 7); R(486, 924, 510, 944, (220, 60, 50), (0, 0, 0), 2)     # 칠장이 + 붓
car(470, 890); R(480, 1034, 540, 1070, WOOD, (0, 0, 0), 4); R(600, 1034, 660, 1070, WOOD, (0, 0, 0), 4)                                    # 받침대(나무 토막)에 올린 객차 — 바퀴는 가림
R(476, 1006, 664, 1034, (176, 192, 208), None)
for k, col in enumerate([(70, 170, 80), (60, 120, 220), (220, 60, 50), (245, 205, 60)]):                                                   # 페인트 통 넷
    x = 706 + k * 56; R(x, 1020, x + 46, 1078, (200, 200, 205), (0, 0, 0), 3); E(x + 23, 1020, 23, 8, col, (0, 0, 0), 3)
# ── 앞마당 오른쪽: 사슬의 행선지
# 멀리 작은 카키 막사 — 지붕에 보라 짝이 앉아 사슬(앞 끝 빨강)을 지붕 구멍으로
P([(930, 880), (950, 820), (1130, 820), (1150, 880)], (170, 160, 100)); R(940, 880, 1140, 930, (190, 180, 120))
C(1030, 806, 18, PUR, (0, 0, 0), 3); C(1030, 784, 11, PUR, (0, 0, 0), 3); [C(1058 + k * 9, 812 + k * 6, 5, (220, 60, 50) if k == 2 else (240, 195, 60), (0, 0, 0), 1) for k in range(3)]
# 이정표: 기둥 + 화살판 셋(구슬 자리는 비움)
R(1284, 800, 1298, 1096, WOOD, (0, 0, 0), 3)
P([(1180, 820), (1284, 820), (1284, 856), (1180, 856), (1158, 838)], (235, 215, 170))        # ← 막사
P([(1298, 872), (1402, 872), (1424, 890), (1402, 908), (1298, 908)], (235, 215, 170))        # → 손님채
P([(1298, 924), (1402, 924), (1424, 942), (1402, 960), (1298, 960)], (235, 215, 170))        # → 꼬투리
# 짐꾼: 다 꿰어진 구슬 사슬을 어깨에 메고 오른쪽으로
man(1500, 1090, (190, 90, 60), h=170)
pts = [(1560, 950), (1530, 930), (1500, 926), (1470, 934), (1446, 956), (1432, 988), (1428, 1022), (1432, 1056)]
for k, (bx, by) in enumerate(pts): C(bx, by, 11, [(240, 195, 60), (240, 130, 40), (240, 120, 170), (110, 190, 235)][k % 4], (0, 0, 0), 2)
# 콩 모양 손님채(앞을 터 안쪽 빨간 주름 커튼이 보임) + 뒤의 오두막 지붕 초록 꼬투리
R(1900, 780, 1990, 850, (190, 150, 100)); P([(1888, 780), (1945, 748), (2002, 780)], (150, 100, 60)); E(1945, 752, 44, 12, (110, 190, 80))
P([(1650, 960), (1670, 880), (1740, 842), (1830, 856), (1900, 836), (1980, 868), (2010, 950), (1990, 1040), (1900, 1084), (1760, 1084), (1680, 1050)], (245, 232, 200))
P([(1700, 960), (1716, 904), (1760, 880), (1830, 892), (1890, 876), (1946, 900), (1966, 956), (1950, 1024), (1890, 1056), (1770, 1056), (1716, 1030)], (200, 50, 50))
for k in range(7): L([(1730 + k * 34, 892 + (k % 2) * 8), (1726 + k * 34, 1040)], (140, 25, 30), 4)
im = im.resize((W, H), Image.LANCZOS); im.save(f'{OUT}/sketch_2048.png')
im.resize((1024, 572), Image.LANCZOS).save(f'{OUT}/sketch.png')
