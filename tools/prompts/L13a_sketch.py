#!/usr/bin/env python3
# L13a_sketch.py — L13a 「성 방어전 한눈에」 바탕용 배치 밑그림(성 안에서 본 그림 — 회색 돌 성벽이 위쪽 띠)
# 2048x1144 로 그려 1024x572 로 줄인다(Gemini 에 올리는 것은 sketch.png).
# Gemini 가 그릴 것만: 성벽과 무너진 틈 · 봉화 · 침입자 셋 · 파리채 경비 · 삼키는 흰 덩이 · 요금소 초소 · 자루 초소 · 궁수와 망루 · 집과 인터폰과 주민 셋 · 내성 탑과 발코니의 병정 둘 · 벌 · 문간의 잠옷 병정.
# ⚠ 도랑물 · 수배 전단의 그림 · 조끼 단추 · 주민의 배지는 여기 그리지 않는다 — PIL(L13a_pil.py).
import math, sys
from PIL import Image, ImageDraw
OUT = sys.argv[1] if len(sys.argv) > 1 else '.'
W, H = 2048, 1144; S = 2
GROUND, STONE, STONE_D = (240, 233, 205), (168, 170, 176), (110, 112, 120)
SKIN = (250, 205, 170); WHITE = (250, 250, 250); GREEN = (110, 190, 90)
im = Image.new('RGB', (W * S, H * S), GROUND); d = ImageDraw.Draw(im)
def sc(pts): return [(x * S, y * S) for x, y in pts]
def R(x0, y0, x1, y1, fill, outline=(0, 0, 0), w=4): d.rectangle([x0 * S, y0 * S, x1 * S, y1 * S], fill=fill, outline=outline, width=w * S if outline else 0)
def C(x, y, r, fill, outline=(0, 0, 0), w=4): d.ellipse([(x - r) * S, (y - r) * S, (x + r) * S, (y + r) * S], fill=fill, outline=outline, width=w * S if outline else 0)
def E(x, y, rx, ry, fill, outline=(0, 0, 0), w=4): d.ellipse([(x - rx) * S, (y - ry) * S, (x + rx) * S, (y + ry) * S], fill=fill, outline=outline, width=w * S if outline else 0)
def L(pts, fill=(0, 0, 0), w=6): d.line(sc(pts), fill=fill, width=w * S, joint='curve')
def P(pts, fill, outline=(0, 0, 0), w=4):
    d.polygon(sc(pts), fill=fill)
    if outline: d.line(sc(pts + [pts[0]]), fill=outline, width=w * S)
def person(x, y, h, coat, hat=None):
    """발이 (x, y) 인 사람 자리표."""
    bw = h // 7
    R(x - bw, y - h * 0.78, x + bw, y - h * 0.36, coat); L([(x - bw // 2, y - h * 0.36), (x - bw // 2, y)], w=8); L([(x + bw // 2, y - h * 0.36), (x + bw // 2, y)], w=8)
    C(x, y - h * 0.88, h // 9, SKIN)
    if hat: R(x - h // 9, y - h * 1.02, x + h // 9, y - h * 0.94, hat, (0, 0, 0), 3)
def germ(x, y, an=0):
    """화난 초록 알약 세균 + 꼬리."""
    E(x, y, 26, 44, GREEN); L([(x - 12, y - 20), (x - 2, y - 14)], w=4); L([(x + 12, y - 20), (x + 2, y - 14)], w=4)
    L([(x, y + 44), (x + 14, y + 70), (x - 8, y + 92), (x + 10, y + 112)], (60, 130, 60), 5)

# ── 성벽(위쪽 띠 · 회색 돌 · 흉벽) + 무너진 틈
R(0, 0, W, 46, (190, 222, 240), None)
R(0, 46, W, 214, STONE, None)
for r in range(6):
    y = 46 + r * 28; L([(0, y), (W, y)], STONE_D, 3)
    for x in range(-70 + (r % 2) * 70, W, 140): L([(x, y), (x, y + 28)], STONE_D, 3)
for x in range(0, W, 150): R(x, 0, x + 70, 46, STONE, (0, 0, 0), 4)
L([(0, 214), (W, 214)], (0, 0, 0), 6)
P([(548, 0), (716, 0), (690, 110), (720, 214), (540, 214), (566, 120)], GROUND, None)                    # 틈
for cx, cy in ((530, 236), (600, 246), (690, 240), (742, 232)): P([(cx - 26, cy + 14), (cx - 8, cy - 14), (cx + 24, cy - 6), (cx + 20, cy + 16)], STONE)
# 봉화(성벽 위 불 바구니)
R(1150, 20, 1230, 70, (70, 70, 76)); P([(1160, 20), (1176, -30), (1190, 0), (1204, -40), (1220, 20)], (250, 150, 40))
# ── 침입자: 틈으로 들어오는 화난 초록 세균 둘 + 망토 사람(두루마리)
germ(600, 150); germ(668, 210)
P([(604, 20), (650, 20), (668, 120), (590, 120)], (90, 60, 120)); C(627, 6, 22, (90, 60, 120)); R(644, 70, 690, 86, (250, 248, 236), (0, 0, 0), 3)
# ── 파리채 경비(틈 왼쪽)
person(450, 470, 230, WHITE, WHITE); L([(476, 300), (540, 250)], (120, 90, 50), 7); R(528, 206, 580, 260, (120, 200, 120), (0, 0, 0), 3)
# ── 커다란 입의 둥근 흰 덩이(맨 왼쪽)
C(230, 420, 130, WHITE); E(270, 440, 70, 52, (190, 60, 60)); germ(330, 430)
# ── 요금소 초소(성벽에 붙음) + 나무 가로대 · 창구의 경비
R(770, 150, 930, 430, (190, 140, 90)); P([(752, 150), (850, 96), (948, 150)], (150, 100, 60)); R(800, 220, 900, 320, (60, 50, 44)); C(850, 280, 30, SKIN); R(826, 236, 874, 252, WHITE, (0, 0, 0), 3)
L([(770, 400), (590, 400)], (150, 100, 60), 12)
# ── 큰 천 자루에 난 창구(자루 초소)
P([(1050, 470), (1040, 330), (1090, 276), (1180, 276), (1232, 330), (1222, 470)], (200, 170, 120)); L([(1090, 276), (1136, 244), (1180, 276)], (140, 110, 70), 8)
R(1096, 340, 1176, 420, (60, 50, 44)); C(1136, 388, 26, SKIN)
# ── 망루 위의 흰 옷 궁수(왼쪽 아래)
R(60, 860, 220, 880, (150, 100, 60)); L([(76, 880), (66, 1010)], (150, 100, 60), 10); L([(204, 880), (214, 1010)], (150, 100, 60), 10)
person(140, 860, 220, WHITE, WHITE); L([(180, 650), (236, 720), (180, 790)], (120, 80, 40), 6); L([(180, 650), (180, 790)], (60, 60, 60), 2)
# ── 집(인터폰) + 주민 셋
R(330, 700, 600, 960, (236, 222, 196)); P([(306, 700), (465, 590), (624, 700)], (150, 96, 70)); R(430, 840, 500, 960, (120, 80, 50))
R(540, 760, 584, 830, (90, 96, 110)); C(562, 780, 10, (30, 30, 30), None)
person(680, 1010, 200, (200, 120, 90)); person(760, 1010, 190, (120, 150, 200)); person(830, 1010, 140, (220, 190, 90))
# ── 내성(둥근 돌탑) + 발코니의 병정 둘 · 벌 + 문간의 잠옷 병정
R(1470, 90, 2020, 1144, STONE); 
for r in range(36):
    y = 90 + r * 30; L([(1470, y), (2020, y)], STONE_D, 2)
P([(1440, 90), (1745, -60), (2050, 90)], (120, 70, 60))
R(1500, 560, 1990, 590, (150, 100, 60)); 
for x in range(1510, 1990, 60): L([(x, 500), (x, 560)], (150, 100, 60), 8)
L([(1500, 500), (1990, 500)], (150, 100, 60), 8)
for x, vest in ((1600, (120, 120, 126)), (1760, (120, 120, 126))):
    person(x, 560, 250, (200, 50, 50), (30, 30, 34)); R(x - 30, 380, x + 30, 460, vest, (0, 0, 0), 3)
E(1900, 470, 56, 40, (250, 210, 60)); [L([(1870 + k * 26, 434), (1870 + k * 26, 506)], w=8) for k in range(3)]; L([(1930, 440), (1950, 340)], (120, 80, 40), 5); P([(1950, 340), (2006, 356), (1950, 380)], (200, 160, 90))
R(1640, 880, 1800, 1110, (100, 70, 50))
person(1560, 1090, 210, (150, 190, 230)); L([(1590, 1010), (1640, 1060)], w=8); R(1470, 960, 1530, 1040, (250, 248, 236), (0, 0, 0), 3); R(1596, 950, 1640, 1010, (150, 60, 60), (0, 0, 0), 3)

im = im.resize((W, H), Image.LANCZOS); im.save(f'{OUT}/sketch_full.png'); im.resize((1024, 572), Image.LANCZOS).save(f'{OUT}/sketch.png')
print('ok', f'{OUT}/sketch.png')
