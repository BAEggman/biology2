L([(D2 + 40, 300), (D2 + 40, 190)], (60, 150, 60), 8)
for a in range(0, 360, 36): C(D2 + 40 + 30 * math.cos(math.radians(a)), 160 + 30 * math.sin(math.radians(a)), 11, (250, 200, 30), (0, 0, 0), 2)
