# L53c_sketch.py — L53c 「동전 펌프와 짝 손님」 바탕용 배치 밑그림(2048x1144 → 1024x572).
import math, sys
from PIL import Image, ImageDraw
OUT = sys.argv[1] if len(sys.argv) > 1 else '.'
W, H = 2048, 1144; S = 2
im = Image.new('RGB', (W * S, H * S), (120, 190, 235)); d = ImageDraw.Draw(im)
def R(x0, y0, x1, y1, fill, outline=(0, 0, 0), w=4): d.rectangle([x0 * S, y0 * S, x1 * S, y1 * S], fill=fill, outline=outline, width=w * S if outline else 0)
def RR(x0, y0, x1, y1, r, fill, outline=(0, 0, 0), w=4): d.rounded_rectangle([x0 * S, y0 * S, x1 * S, y1 * S], radius=r * S, fill=fill, outline=outline, width=w * S if outline else 0)
def C(x, y, r, fill, outline=(0, 0, 0), w=4): d.ellipse([(x - r) * S, (y - r) * S, (x + r) * S, (y + r) * S], fill=fill, outline=outline, width=w * S if outline else 0)
def E(x, y, rx, ry, fill, outline=(0, 0, 0), w=4): d.ellipse([(x - rx) * S, (y - ry) * S, (x + rx) * S, (y + ry) * S], fill=fill, outline=outline, width=w * S if outline else 0)
def L(pts, fill=(0, 0, 0), w=6): d.line([(x * S, y * S) for x, y in pts], fill=fill, width=w * S, joint='curve')
def P(pts, fill, outline=(0, 0, 0), w=4):
    d.polygon([(x * S, y * S) for x, y in pts], fill=fill)
    if outline: d.line([(x * S, y * S) for x, y in pts + [pts[0]]], fill=outline, width=w * S)
def ARC(x, y, r, a0, a1, fill=(0, 0, 0), w=5): d.arc([(x - r) * S, (y - r) * S, (x + r) * S, (y + r) * S], a0, a1, fill=fill, width=w * S)
def ARROW(x, y0, y1, w=6):
    L([(x, y0), (x, y1)], w=w); s = 1 if y1 > y0 else -1
    P([(x, y1 + s * 16), (x - 13, y1 - s * 4), (x + 13, y1 - s * 4)], (0, 0, 0), None)
TOP, BOT = 440, 700
RED, BLUE = (225, 45, 40), (40, 80, 200)
WAT_UP, WAT_DN, BUT, LUM = (120, 190, 235), (40, 110, 190), (250, 214, 80), (190, 225, 245)
BRASS, GOLD = (200, 160, 60), (240, 190, 40)
R(0, 0, W, 70, (200, 232, 250), None); R(0, 70, W, TOP, WAT_UP, None); R(0, BOT, W, H, WAT_DN, None)
L([(0, 70), (W, 70)], (30, 80, 140), 5)
R(0, TOP, W, BOT, BUT, None); L([(0, TOP), (W, TOP)], w=6); L([(0, BOT), (W, BOT)], w=6)
def buoy(x, top=True, r=27):
    col = RED if top else BLUE
    y0 = TOP if top else BOT; sgn = 1 if top else -1; leg = 112
    for dx in (-11, 11): L([(x + dx, y0), (x + dx + 22, y0 + sgn * leg * 0.5), (x + dx - 4, y0 + sgn * leg)], (60, 20, 20), 6)
    hy = y0 - sgn * (r - 2); C(x, hy, r, col); R(x - r + 5, hy - 7, x + r - 5, hy + 7, (255, 255, 255), (0, 0, 0), 2)
def sack(x, y, r=22, col=(255, 255, 255)):
    P([(x - r, y + r), (x - r * 0.9, y - r * 0.5), (x - r * 0.35, y - r), (x + r * 0.35, y - r), (x + r * 0.9, y - r * 0.5), (x + r, y + r)], col); L([(x - r * 0.4, y - r * 0.8), (x + r * 0.4, y - r * 0.8)], (120, 80, 40), 4)
def knife(x, y, s=1.0, ang=0):
    ca, sa = math.cos(math.radians(ang)), math.sin(math.radians(ang))
    def T(px, py): return (x + (px * ca - py * sa) * s, y + (px * sa + py * ca) * s)
    P([T(-7, 8), T(-7, -30), T(0, -46), T(7, -30), T(7, 8)], (215, 220, 228), (0, 0, 0), 3); P([T(-6, 8), T(6, 8), T(6, 34), T(-6, 34)], (70, 50, 40), (0, 0, 0), 3)
GR = (130, 60, 170)
def grape(x, y, r=17): C(x, y, r, GR)
def lemon(x, y, r=17): E(x, y, r + 5, r - 2, (250, 225, 60)); P([(x + r + 3, y - 4), (x + r + 12, y), (x + r + 3, y + 4)], (250, 225, 60), (0, 0, 0), 2)
def pebble(x, y, r=13): E(x, y, r + 2, r - 2, (150, 150, 155))
cols = [(230, 60, 60), (60, 160, 230), (250, 200, 50), (90, 190, 90), (170, 90, 200), (245, 140, 40)]
def column(x, y0, y1, r=15, k0=0):
    y = y0; i = k0
    while y <= y1: C(x, y, r, cols[i % 6], (0, 0, 0), 3); y += 2 * r - 2; i += 1
def pod(xc):
    """회전문 기둥: 구슬 줄 둘이 둥근 빈 창을 감싼다(창 안의 문짝 · 손님은 PIL 로 그린다)."""
    def off(y): return 40 + 38 * math.exp(-((y - 570) / 120.0) ** 2)
    pts = [(xc - off(y) + 14, y) for y in range(300, 881, 10)] + [(xc + off(y) - 14, y) for y in range(880, 299, -10)]
    P(pts, LUM, None)
    y = 300; i = 0
    while y <= 880:
        C(xc - off(y), y, 15, cols[i % 6], (0, 0, 0), 3); C(xc + off(y), y, 15, cols[(i + 3) % 6], (0, 0, 0), 3); y += 28; i += 1
    for a0, a1 in ((289, 71), (109, 251)): ARC(xc, 570, 60, a0, a1, (150, 110, 40), 11)
# ───────── 왼쪽: 큰 동전 펌프(Na+-K+ 펌프) ─────────
buoy(60); buoy(60, top=False)
RR(130, 360, 600, 780, 26, BRASS, (0, 0, 0), 6)
for x, y in [(160, 390), (570, 390), (160, 750), (570, 750)]: C(x, y, 9, (235, 215, 150), (0, 0, 0), 2)
R(300, 352, 430, 420, LUM, None); R(300, 722, 430, 788, LUM, None)                # 위 · 아래 트임
C(365, 570, 162, LUM, (0, 0, 0), 6)
L([(600, 560), (650, 560), (650, 610)], (90, 95, 105), 10); C(650, 618, 11, (60, 40, 30))    # 크랭크
R(520, 772, 556, 786, (30, 20, 10), None); E(538, 850, 14, 20, GOLD); ARROW(538, 824, 800, 5)   # 투입구 · 동전
C(165, 500, 24, (220, 40, 40), (0, 0, 0), 4); R(152, 440, 178, 478, (150, 100, 50), (0, 0, 0), 3)   # 왼쪽: 붉은 도장을 찍음
C(578, 690, 20, (220, 40, 40), (0, 0, 0), 4); C(592, 800, 18, (220, 40, 40), (0, 0, 0), 4); L([(585, 720), (590, 770)], w=3)   # 오른쪽: 붉은 도장이 떨어짐
# 위 물: 소금 자루 무리(왼쪽 위) · 막 나온 자루 · 들어가려는 칼 둘
for x, y in [(60, 120), (150, 95), (245, 130), (60, 235), (150, 215), (250, 250), (100, 330)]: sack(x, y, 22)
sack(330, 315, 22); sack(300, 250, 22)
knife(440, 330, 1.0, 0); knife(505, 240, 1.0, 12)
# 아래 물: 타려는 자루 셋 · 칼 무리(오른쪽 아래)
for x, y in [(300, 835), (255, 890), (335, 895)]: sack(x, y, 22)
for x, y, a in [(430, 850, 0), (480, 900, 10), (545, 955, -8), (420, 975, 6), (500, 1030, 0), (590, 900, 0), (610, 1010, 10)]: knife(x, y, 0.95, a)
# ───────── 건전지(막전위) + 전선 ─────────
buoy(672, r=24); buoy(672, top=False, r=24)
BX = 750
RR(BX - 45, 330, BX + 45, 800, 14, (60, 62, 70), (0, 0, 0), 5); R(BX - 43, 332, BX + 43, 470, (235, 150, 40), None); R(BX - 18, 300, BX + 18, 332, (190, 190, 195), (0, 0, 0), 4)
L([(BX - 15, 400), (BX + 15, 400)], (0, 0, 0), 6); L([(BX, 385), (BX, 415)], (0, 0, 0), 6); L([(BX - 15, 745), (BX + 15, 745)], (255, 255, 255), 6)
L([(590, 380), (630, 290), (690, 250), (BX, 300)], (200, 40, 40), 7)                              # 펌프 → 건전지 전선(번쩍)
for x, y in [(630, 268), (690, 232)]: P([(x, y - 14), (x + 6, y - 3), (x + 14, y - 3), (x + 4, y + 14), (x + 6, y + 3), (x - 4, y + 3)], (255, 225, 40), (0, 0, 0), 2)
IX = 868
buoy(IX, r=24); buoy(IX, top=False, r=24)
sack(IX - 6, 330, 22); L([(IX + 20, 300), (IX + 36, 300)], w=4); L([(IX + 28, 292), (IX + 28, 308)], w=4); ARROW(IX - 42, 360, 410, 5)   # ＋ 소금 자루는 안으로
E(IX, 835, 34, 22, (245, 240, 230)); C(IX + 33, 815, 14, (245, 240, 230)); L([(IX + 39, 805), (IX + 47, 789)], w=4); L([(IX + 29, 805), (IX + 27, 789)], w=4)   # 염소(아래 물)
for dx in (-18, -4, 10, 22): L([(IX + dx, 853), (IX + dx, 881)], w=4)
