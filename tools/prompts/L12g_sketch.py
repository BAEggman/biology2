#!/usr/bin/env python3
# L12g_sketch.py — L12g 「운하 끝 늪과 목장 — 대장 · 장내 미생물 · 초식동물의 적응 · 필수 영양소」 바탕용 배치 밑그림
# 2048x1144 로 그려 1024x572 로 줄인다(Gemini 에 올리는 것은 sketch.png).
# 세 구역: 아래 띠 = 운하의 마지막 구간(대장 · 왼 → 오) / 왼쪽 위 = 세균 마을 / 오른쪽 위 = 목장 / 가운데 위 = 먹거리 좌판.
# ⚠ 세어야 하는 것(구슬 여덟 · 소 속의 화살 · 가위표)은 여기 그리지 않는다 — PIL 로 얹는다.
import math, sys
from PIL import Image, ImageDraw
OUT = sys.argv[1] if len(sys.argv) > 1 else '.'
W, H = 2048, 1144; S = 2
SKY, GRASS, STONE, STEEL = (200, 230, 248), (150, 205, 120), (176, 170, 160), (165, 172, 182)
MUD1, MUD2, MUD3 = (205, 170, 120), (165, 120, 75), (120, 80, 45)
GERM = (104, 190, 84)
im = Image.new('RGB', (W * S, H * S), SKY); d = ImageDraw.Draw(im)
def sc(pts): return [(x * S, y * S) for x, y in pts]
def R(x0, y0, x1, y1, fill, outline=(0, 0, 0), w=4): d.rectangle([x0 * S, y0 * S, x1 * S, y1 * S], fill=fill, outline=outline, width=w * S if outline else 0)
def RR(x0, y0, x1, y1, r, fill, outline=(0, 0, 0), w=4): d.rounded_rectangle([x0 * S, y0 * S, x1 * S, y1 * S], radius=r * S, fill=fill, outline=outline, width=w * S if outline else 0)
def C(x, y, r, fill, outline=(0, 0, 0), w=4): d.ellipse([(x - r) * S, (y - r) * S, (x + r) * S, (y + r) * S], fill=fill, outline=outline, width=w * S if outline else 0)
def E(x, y, rx, ry, fill, outline=(0, 0, 0), w=4): d.ellipse([(x - rx) * S, (y - ry) * S, (x + rx) * S, (y + ry) * S], fill=fill, outline=outline, width=w * S if outline else 0)
def L(pts, fill=(0, 0, 0), w=6): d.line(sc(pts), fill=fill, width=w * S, joint='curve')
def P(pts, fill, outline=(0, 0, 0), w=4):
    d.polygon(sc(pts), fill=fill)
    if outline: d.line(sc(pts + [pts[0]]), fill=outline, width=w * S)
def man(x, y, body, head=(250, 205, 170), h=120):
    bw = max(14, h // 6); hr = max(16, h // 6)
    R(x - bw, y - h, x + bw, y - h * 0.3, body); L([(x - bw // 2, y - h * 0.3), (x - bw // 2 - 3, y)], w=8); L([(x + bw // 2, y - h * 0.3), (x + bw // 2 + 3, y)], w=8)
    C(x, y - h - hr + 4, hr, head)
def germ(x, y, s=1.0, col=GERM):
    """웃는 초록 알약 세균(팔다리)."""
    RR(x - 16 * s, y - 34 * s, x + 16 * s, y + 30 * s, 16 * s, col, (0, 0, 0), 3)
    C(x - 6 * s, y - 14 * s, 3 * s, (0, 0, 0), None); C(x + 6 * s, y - 14 * s, 3 * s, (0, 0, 0), None); L([(x - 7 * s, y - 2 * s), (x, y + 4 * s), (x + 7 * s, y - 2 * s)], w=2)
    L([(x - 8 * s, y + 30 * s), (x - 10 * s, y + 44 * s)], w=3); L([(x + 8 * s, y + 30 * s), (x + 10 * s, y + 44 * s)], w=3)

# ── 땅
R(0, 330, W, H, GRASS, None)
# ── 아래 띠: 운하의 마지막 구간(대장)
R(0, 800, W, 1090, STONE); R(0, 1090, W, H, (150, 110, 70), None)
R(0, 822, 430, 1068, (214, 196, 160), None)                                        # 들어오는 묽은 물
for k in range(60):                                                                 # 묽은 흙탕 → 되직한 진흙
    x0 = 430 + k * 18; t = k / 59
    col = tuple(int(MUD1[i] + (MUD3[i] - MUD1[i]) * t) for i in range(3)); R(x0, 822, x0 + 19, 1068, col, None)
for x in (1180, 1260, 1340, 1420):                                                  # 진흙 벽돌 — 풀 줄기 깔개를 탔다
    for yy in (900, 980):
        xx = x + (20 if yy == 980 else 0)
        for k in range(3): L([(xx - 14, yy + 44 + k * 5), (xx + 78, yy + 44 + k * 5)], (60, 150, 60), 3)
        RR(xx, yy, xx + 64, yy + 46, 6, MUD3, (0, 0, 0), 3)
for x in (560, 760, 960):                                                           # 둑의 노란 스펀지(물을 빨아들임)
    RR(x, 770, x + 110, 850, 10, (250, 215, 70), (0, 0, 0), 4)
    for dx, dy in [(20, -30), (55, -44), (88, -28)]: C(x + dx, 770 + dy, 8, (120, 190, 240), (0, 0, 0), 2)
for x in (640, 880, 1060):                                                          # 진흙 속 초록 풀 줄기(섬유)
    for k in range(4): L([(x + k * 12, 960 + k * 6), (x + 70 + k * 12, 940 + k * 6)], (60, 150, 60), 4)
# 막다른 둥근 못(맹장) + 지렁이 꼴 창고(충수)
E(310, 760, 120, 90, STONE); E(310, 760, 96, 68, (214, 196, 160))
L([(200, 740), (150, 760), (90, 742), (60, 692), (80, 642), (130, 622)], (0, 0, 0), 66); L([(200, 740), (150, 760), (90, 742), (60, 692), (80, 642), (130, 622)], (190, 150, 110), 58)   # 굽은 지렁이 몸(꼬리는 못에)
C(130, 622, 33, (0, 0, 0), None); C(130, 622, 29, (190, 150, 110), None)
for (ax, ay, bx, by) in [(170, 720, 178, 776), (118, 724, 100, 780), (50, 714, 100, 678), (48, 662, 104, 672), (60, 620, 104, 644)]: L([(ax, ay), (bx, by)], (120, 85, 55), 3)   # 고리 마디
R(70, 662, 140, 722, (240, 225, 190), (0, 0, 0), 3)
for x in (82, 105, 128): RR(x - 9, 672, x + 9, 714, 5, (200, 230, 240), (0, 0, 0), 2); C(x, 694, 5, GERM, None)
# 헛간(직장) — 진흙 벽돌을 쌓아 둠
R(1580, 740, 1800, 1090, (190, 150, 100)); P([(1562, 740), (1690, 660), (1818, 740)], (150, 90, 60)); R(1606, 820, 1774, 1070, (90, 60, 40))
for r in range(4):
    for c in range(3): RR(1616 + c * 52, 1010 - r * 48, 1664 + c * 52, 1052 - r * 48, 5, MUD3, (0, 0, 0), 2)
# 나가는 관 + 입술 둘
R(1800, 900, W + 10, 1010, STEEL)
E(1850, 955, 22, 62, (220, 60, 70)); E(1850, 955, 8, 40, (120, 20, 30))
E(1960, 955, 22, 62, (220, 60, 70)); E(1960, 955, 8, 40, (120, 20, 30))
man(1990, 890, (60, 90, 160), h=90); L([(1978, 840), (1962, 892)], (90, 90, 100), 7)      # 바깥 입술의 지렛대를 쥔 사람
# ── 왼쪽 위 구석: 작은 강철 통(위) + 헬리콥터 날개 세균
RR(30, 70, 280, 320, 46, STEEL, (0, 0, 0), 6); RR(54, 94, 256, 300, 34, (150, 220, 130), (0, 0, 0), 3); R(56, 96, 254, 170, (208, 214, 220), None)
germ(196, 190, 0.9); L([(160, 150), (232, 150)], w=5); L([(196, 150), (196, 160)], w=4); C(250, 214, 16, (120, 60, 50), (0, 0, 0), 3)
# ── 세균 마을(왼쪽 가운데)
man(470, 700, (60, 110, 190), h=150); germ(590, 640, 2.0); L([(500, 610), (552, 620)], w=8)        # 운하지기와 세균의 악수
L([(624, 620), (660, 590)], w=6); P([(654, 596), (668, 530), (680, 534), (674, 600)], (220, 225, 232), (0, 0, 0), 2); R(650, 592, 680, 606, (120, 80, 50), (0, 0, 0), 2); C(664, 612, 7, (220, 50, 50), (0, 0, 0), 2)   # 다른 손의 선물 리본 칼
P([(640, 360), (700, 360), (760, 500), (720, 520)], (170, 120, 70)); E(760, 540, 40, 16, (255, 255, 255))   # 먹이 홈통 → 그릇
for x in (720, 800): germ(x, 600, 0.8)
R(830, 520, 930, 640, (240, 220, 180)); P([(815, 520), (880, 460), (945, 520)], (190, 80, 60)); R(865, 580, 895, 640, (120, 80, 50))   # 아늑한 작은 집
germ(256, 606, 0.8); P([(274, 600), (296, 590), (296, 610)], (170, 170, 175), (0, 0, 0), 2)     # 흙손으로 타일을 까는 세균
for k in range(4): R(300 + k * 30, 590, 328 + k * 30, 618, (200, 220, 235), (0, 0, 0), 2)
man(425, 470, (252, 252, 252), h=95); R(408, 352, 442, 364, (252, 252, 252), (0, 0, 0), 2); germ(490, 440, 0.8)   # 흰 옷 경비 + 파리채를 건네는 세균
L([(476, 436), (452, 400)], (60, 150, 90), 4); R(436, 372, 462, 402, (90, 190, 120), (0, 0, 0), 2)
# 진흙 덩이를 옮겨 심는 정원사 + 잿빛 못
man(100, 505, (70, 150, 80), h=105); P([(70, 372), (130, 372), (116, 356), (84, 356)], (230, 200, 120), (0, 0, 0), 2)     # 밀짚모자 농부
E(262, 520, 88, 30, (190, 190, 190)); L([(210, 520), (240, 512), (262, 526), (300, 516)], (120, 120, 120), 2); L([(250, 500), (262, 526), (255, 544)], (120, 120, 120), 2)   # 말라붙어 금 간 잿빛 못
L([(124, 440), (196, 496)], (120, 80, 50), 6); E(206, 498, 28, 14, MUD2); germ(206, 484, 0.5)                              # 삽 끝의 진흙 덩이 + 웃는 세균
# ── 가운데 위: 먹거리 좌판
R(440, 210, 900, 240, (170, 120, 70)); L([(450, 240), (450, 320)], w=6); L([(890, 240), (890, 320)], w=6)
P([(430, 120), (910, 120), (880, 80), (460, 80)], (220, 70, 60))
R(456, 150, 566, 210, (190, 150, 100)); [C(476 + k * 22, 170 + (k % 2) * 16, 12, (245, 200, 40), (0, 0, 0), 2) for k in range(4)]      # 동전 궤짝
R(590, 150, 700, 210, (190, 150, 100)); [R(600 + k * 32, 164 + (k % 2) * 18, 628 + k * 32, 180 + (k % 2) * 18, (170, 170, 175), (0, 0, 0), 2) for k in range(3)]   # 낱장 벽돌 궤짝
R(724, 150, 890, 210, (190, 150, 100)); RR(736, 160, 836, 200, 6, (215, 180, 130), (0, 0, 0), 2)                                       # 「못 만드는 것」 궤짝(빈 구슬 쟁반)
RR(846, 150, 884, 206, 8, (120, 160, 120), (0, 0, 0), 2); C(866, 150, 12, (250, 205, 60), (0, 0, 0), 2)                               # 장판 두루마리 + 노란 기름방울
man(350, 320, (240, 200, 60), head=(245, 210, 70), h=130); R(300, 150, 330, 180, (255, 255, 255)); R(296, 196, 334, 226, (150, 110, 70))   # 통옥수수 탈 장수(쌀밥 공기 · 여행 가방 자리)
man(1200, 320, (130, 170, 90), head=(150, 190, 110), h=130); L([(1262, 150), (1262, 320)], (120, 80, 50), 8)                             # 콩 탈 장수 + 기둥
R(1272, 170, 1326, 208, (200, 160, 90), (0, 0, 0), 3); L([(1299, 170), (1299, 208)], (240, 230, 200), 3); L([(1272, 189), (1326, 189)], (240, 230, 200), 3); L([(1299, 170), (1299, 156), (1266, 156)], (240, 230, 200), 3)   # 끈으로 묶어 매단 메주
R(940, 220, 1000, 320, (200, 160, 110)); C(970, 190, 22, (250, 205, 170)); R(950, 214, 990, 226, (255, 255, 255)); L([(990, 214), (1006, 186)], w=4); C(1008, 178, 9, (230, 90, 160), (0, 0, 0), 2)   # 유아 의자의 아기 + 치켜든 구슬
R(1030, 250, 1130, 266, (170, 120, 70)); man(1080, 250, (150, 90, 60), h=70); C(1060, 240, 10, (250, 205, 60), (0, 0, 0), 2)           # 작업대 — 집게가 부러진 일꾼
# ── 목장: 속을 갈라 보인 소(왼쪽을 봄)
E(1400, 450, 250, 165, (250, 250, 245)); P([(1190, 360), (1110, 330), (1090, 420), (1150, 470), (1210, 450)], (250, 250, 245))
for x in (1250, 1330, 1480, 1560): R(x, 590, x + 34, 720, (250, 250, 245))
E(1420, 420, 110, 86, (190, 150, 100)); E(1300, 500, 40, 42, (230, 190, 90)); R(1380, 530, 1460, 600, (220, 200, 170)); RR(1486, 512, 1580, 606, 20, STEEL, (0, 0, 0), 5); RR(1498, 548, 1568, 596, 12, (150, 220, 130), (0, 0, 0), 2)
for (hx, hy) in [(1286, 490), (1306, 490), (1296, 506), (1316, 508), (1284, 520), (1304, 524)]: C(hx, hy, 8, (230, 190, 90), (0, 0, 0), 1)   # 벌집 무늬
for k in range(5): L([(1392 + k * 14, 536), (1392 + k * 14, 594)], w=2)
L([(1320, 400), (1220, 384), (1160, 400)], (230, 180, 170), 16)
germ(1390, 420, 0.8); E(1456, 440, 30, 16, (200, 170, 220)); [L([(1430 + k * 8, 426), (1428 + k * 8, 418)], w=2) for k in range(8)]
for k in range(5): R(1100 + k * 15, 420, 1114 + k * 15, 442, (255, 255, 255), (0, 0, 0), 2)       # 넓적한 이빨
