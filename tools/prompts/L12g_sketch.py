# 호랑이(단검 이빨) · 아이(두 가지 이빨)
E(1000, 630, 72, 86, (240, 150, 50)); C(1000, 535, 48, (240, 150, 50)); P([(980, 552), (990, 596), (1000, 552)], (255, 255, 255)); P([(1004, 552), (1014, 596), (1024, 552)], (255, 255, 255)); E(1052, 596, 28, 16, (200, 60, 60))
man(1140, 724, (90, 160, 200), h=100); L([(1126, 650), (1104, 626)], w=4); [L([(1104, 626), (1094 + k * 8, 602)], (60, 150, 60), 3) for k in range(4)]; L([(1154, 650), (1176, 628)], w=4); E(1184, 620, 16, 11, (200, 60, 60), (0, 0, 0), 2)   # 아이 하나 — 풀 한 줌 + 고기
# 판자 갉는 흰개미(소 오른쪽 · 헛간 위)
R(1720, 520, 1930, 550, (190, 140, 90)); E(1810, 480, 50, 26, (240, 225, 200)); C(1756, 476, 18, (240, 225, 200)); C(1870, 400, 44, (255, 255, 255)); germ(1860, 400, 0.5); E(1886, 404, 12, 8, (200, 170, 220))
im = im.resize((W, H), Image.LANCZOS); im.save(f'{OUT}/sketch_2048.png')
