#!/usr/bin/env python3
"""s12p05 — B6·B5 결핍을 「사물」로 그렸으므로 사실표에 두 행을 넣는다.

규칙 13(결핍은 상처가 아니라 사물로)에 따라 그림에 넣은 것:
  · 피리 부는 사람 앞 : 붉은 물이 바닥만 남은 유리병 + 요란하게 떠는 양철 컵  → B6 결핍
  · 오른쪽 통 옆      : 발목에 가시 덩굴이 감긴 빈 장화 + 그 위에 늘어진 빈 자루 → B5 결핍

동시에 「하나의 상징은 하나의 사실」로 되돌린다 —
결핍 카드(G1-32·G1-29)를 기능 행에서 떼어 새 결핍 행으로 옮긴다.
DATA 재직렬화 없이 문자열 치환만 한다. 앵커는 전부 정확히 1회여야 한다.
"""
import os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SK = os.path.join(ROOT, 'sketchy.html')

EDITS = [
    # 1. 다리 문구 — 결핍이 어떤 형태로 그려졌는지 읽는 법을 준다
    ('여기는 s12p04의 문 안쪽이다. 결핍이 아니라 <b>조효소</b>를 다룬다. '
     '<b>날달걀이 손을 굳혀 벽돌을 못 붙이게 하는 것</b>이 이 방의 사건이고, 그게 곧 기출이 묻는 자리다.',
     '여기는 s12p04의 문 안쪽이다. 이 방의 본체는 <b>조효소</b>이고, '
     '<b>날달걀이 손을 굳혀 벽돌을 못 붙이게 하는 것</b>이 사건이다 — 그게 곧 기출이 묻는 자리다. '
     '결핍은 사람이 아니라 <b>작업대와 바닥에 놓인 물건</b>으로만 나온다.'),

    # 2. B6 기능 행 — 결핍 카드를 떼고, 접시가 둘인 이유를 명시한다
    ('["피리를 불며 한 접시에서 다른 접시로 꼬리표를 옮김",'
     '"B6 피리독신 — PLP로 아미노산 대사를 돕는다(아미노기 전이). 결핍은 과민반응·경련·빈혈",'
     '["G1-30","G1-31","G1-32"]],',
     '["피리를 불며 한 접시에서 다른 접시로 꼬리표를 옮김",'
     '"B6 피리독신 — PLP로 아미노산 대사를 돕는다. 접시가 둘인 것이 「옮긴다」이다 — 아미노기 전이",'
     '["G1-30","G1-31"]],\n'
     '       ["피리 부는 사람 앞 작업대 — 붉은 물이 바닥만 남은 유리병, 그 옆에서 요란하게 떠는 양철 컵",'
     '"B6 결핍. 비어 가는 붉은 병이 빈혈이고, 멈추지 않고 떠는 컵이 경련·과민반응이다",'
     '["G1-32"]],'),

    # 3. B5 기능 행 — 결핍 카드를 떼고, 결핍 행을 그 뒤에 붙인다
    ('["똑같은 통이 선반 위·바닥 이쪽·바닥 저쪽 세 곳에",'
     '"B5 판토텐산 — pantos(모든 곳)에서 온 이름. 조효소 A를 만들고, 어디에나 있어 결핍이 드물다. '
     '결핍 시 피로·무감각·손발 저림",'
     '["G1-27","G1-28","G1-29"]]]}',
     '["똑같은 통이 선반 위·바닥 이쪽·바닥 저쪽 세 곳에",'
     '"B5 판토텐산 — pantos(모든 곳)에서 온 이름. 조효소 A를 만들고, 어디에나 있어 결핍이 드물다",'
     '["G1-27","G1-28"]],\n'
     '       ["오른쪽 통 옆 바닥 — 발목에 가시 덩굴이 감긴 빈 장화, 그 위에 축 늘어진 빈 자루",'
     '"B5 결핍. 가시 덩굴이 손발 저림·무감각이고, 늘어진 자루가 피로다. '
     '하필 통 셋 옆에 놓인 것이 요점 — 어디에나 있어서 이 자리가 비는 일 자체가 드물다",'
     '["G1-29"]]]}'),
]


def main():
    s = open(SK, encoding='utf-8').read()
    before = s

    for old, new in EDITS:
        n = s.count(old)
        if n != 1:
            print('✗ 앵커가 %d회: %s…' % (n, old[:60]))
            return 1
        s = s.replace(old, new)

    # 확인 ── s12p05 블록만 다시 파싱해 행 수와 카드 ID 를 센다
    i = s.index("{id:'s12p05'")
    d, q, j = 0, None, i
    while j < len(s):
        c = s[j]
        if q:
            if c == '\\':
                j += 2
                continue
            if c == q:
                q = None
        elif c in '"\'`':
            q = c
        elif c == '{':
            d += 1
        elif c == '}':
            d -= 1
            if d == 0:
                break
        j += 1
    blk = s[i:j + 1]
    rows = len(re.findall(r'\[\"', blk.split(',f:[', 1)[1]))
    cards = re.findall(r'"(G1-\d+)"', blk)
    print('s12p05 f 행 %d · 카드 %d개 %s' % (blk.split(',f:[', 1)[1].count('],["') + 1,
                                            len(cards), ' '.join(cards)))
    assert len(cards) == len(set(cards)), '카드 ID 중복 — PMAP 충돌'
    assert '`' not in blk.split('bx:`', 1)[1].split('`', 1)[0] or True

    open(SK, 'w', encoding='utf-8').write(s)
    print('sketchy.html %d → %d bytes' % (len(before), len(s)))
    return 0


if __name__ == '__main__':
    sys.exit(main())
