#!/usr/bin/env python3
"""d05p07 — 표 안에서 같은 수가 앞뒤로 두 번 나오는 자리를 사실표가 짚게 한다.

점검표 ④(한 심볼 = 한 사실)을 훑다 보니 같은 값이 두 띠에 걸쳐 나오는 짝이 둘 있었다.
이건 충돌이 아니라 **같은 줄을 반대편에서 읽은 것**이라, 짚어 주면 오히려 후크가 된다.

  ②표 첫 줄  1,000 중 재조합형 170 → 17 %
  ④표 끝 줄  1,000 중 부모형 830 → 1,000 − 830 = 170 → 17 %     ← 같은 자료다

  ③표 넷째 줄 355·355·145·145 → 교차율 29 %
  ④표 넷째 줄 교차율 29 % → 부모형 71 %                          ← 앞줄의 답이 뒷줄의 문제다
"""
import os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SK = os.path.join(ROOT, 'sketchy.html')

EDITS = [
    ('"<b>부모형 71 %</b>. 마릿수 없이 비율만 물으면 <b>100에서 빼는 것</b>으로 끝난다"',
     '"<b>부모형 71 %</b>. 마릿수 없이 비율만 물으면 <b>100에서 빼는 것</b>으로 끝난다. '
     '★ 이 29 %는 바로 위 ③표 넷째 줄에서 나온 값이다 — <b>앞 띠의 답이 뒤 띠의 문제</b>다"'),

    ('"재조합형은 1,000 − 830 = 170이므로 <b>17 %</b>다. '
     '주어진 것이 부모형이면 <b>빼는 것이 첫걸음</b>이다"',
     '"재조합형은 1,000 − 830 = 170이므로 <b>17 %</b>다. '
     '주어진 것이 부모형이면 <b>빼는 것이 첫걸음</b>이다. '
     '★ 이 줄은 ②표 첫 줄(1,000 중 170)과 <b>같은 자료를 반대편에서 읽은 것</b>이다 — '
     '표의 맨 위와 맨 아래가 한 바퀴를 돌아 만난다"'),
]


def main():
    s = open(SK, encoding='utf-8').read()
    for old, new in EDITS:
        n = s.count(old)
        if n != 1:
            print('✗ 앵커가 %d회: %s…' % (n, old[:60]))
            return 1
        s = s.replace(old, new)
    open(SK, 'w', encoding='utf-8').write(s)
    print('d05p07 — 앞뒤로 만나는 두 자리를 사실표에 박았다 (29 % · 17 %)')
    return 0


if __name__ == '__main__':
    sys.exit(main())
