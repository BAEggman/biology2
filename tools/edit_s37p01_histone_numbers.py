# -*- coding: utf-8 -*-
"""s37p01 재생성 반영 — 히스톤의 숫자·글자를 소품이 나르게 한다.
   사용자 지적:「시험에서는 H2A·H2B·H3·H4 와 H1 의 숫자와 알파벳을 바꿔서 H3A 등으로
   헷갈리게 내기 때문에 2A 2B 3 4 1 을 뇌에 각인시키는 게 필요해」"""
import sys, io
sys.path.insert(0,'/tmp/b2/tools'); import rowlib
P='/tmp/b2/sketchy.html'
s=io.open(P,encoding='utf8').read()

# ── 통의 네 쪽 — 숫자와 글자가 다 소품에 있다 ─────────────────────────────
s,ch,_=rowlib.edit_row(s,'s37p01',4,
  prop='★ 실패의 통이 네 쪽으로 갈라져 있고, 쪽마다 놋쇠 표가 하나씩 붙었다 — '
       '왼쪽부터 <b>가로대 둘</b>짜리 사다리 · <b>배가 둘</b> 불룩한 세로 막대 · '
       '못 <b>셋</b> · 못 <b>넷</b>',
  fact='<b>H2A · H2B · H3 · H4</b> 네 종류다. <b>표에 달린 개수가 곧 번호</b>다 — 2 · 2 · 3 · 4. '
       '★ <b>2가 둘이라 A와 B로 갈린다</b>. 오른쪽 것은 세로 막대에 배가 둘 붙은 <b>B자 모양</b>이라 '
       '헷갈릴 수 없고, 그러면 남은 왼쪽이 <b>A</b>다(왼쪽이 먼저이기도 하다). '
       '★★ 시험은 여기를 섞어 낸다 — <b>H3A</b>·<b>H4B</b> 같은 것은 <b>없다</b>. '
       '글자가 붙는 것은 <b>2뿐</b>이고, 3과 4는 맨숫자다. 실제로는 넷이 각각 두 개씩 모여 8량체를 이룬다')
print('s37p01#4 :', ch)

# ── 밖의 집게 = H1, 못 하나 ────────────────────────────────────────────
s,ch,_=rowlib.edit_row(s,'s37p01',5,
  prop='★ 실이 나가는 목을 잡은 집게 하나 — 통에 속하지 않고 <b>밖</b>에 있고, '
       '붙은 놋쇠 못이 <b>하나</b>뿐이다',
  fact='다섯째 히스톤 <b>H1</b>이다. <b>못이 하나인 것이 곧 1</b>이고, 통 밖에 있는 것이 '
       '「8량체에 안 낀다」는 뜻이다. 뉴클레오솜 사이 연결부에 붙어 더 높은 차원으로 응축시킨다. '
       '그래서 히스톤은 다섯 종류 — <b>넷은 통 안에 둘씩(2A·2B·3·4), 하나는 밖에서 목을 잡는다(1)</b>')
print('s37p01#5 :', ch)

io.open(P,'w',encoding='utf8').write(s)
