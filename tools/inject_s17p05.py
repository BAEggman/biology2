    i = src.index("{id:'s17p04'")
    e = close_brace(src, i)
    rows = []
    for prop, fact, cards in ROWS:
        r = '[' + q2(prop) + ',' + q2(fact)
        if cards: r += ',[' + ','.join(q2(c) for c in cards) + ']'
        rows.append(r + ']')
    panel = ("{id:'s17p05',t:'셋이 버리는 법',br:'" + BR + "',bx:`" + BX + "`,f:["
             + ',\n     '.join(rows) + ']}')
    out = src[:e + 1] + ',\n   ' + panel + src[e + 1:]

    ids = re.findall(r"\{id:'([sd]\d+p\d+[ab]?)'", out)
    assert len(ids) == len(set(ids)), '패널 id 중복'
    b2 = out[out.index("{id:'s17p05'"):]
    b2 = b2[:close_brace(b2, 0) + 1]
    cs = re.findall(r'"([A-Z][A-Z0-9]*(?:-[A-Z0-9]+)*-[\w#]+)"', b2)
    assert len(cs) == len(set(cs)), '카드 중복: ' + str(cs)
    print('s17p05 신설 · 행 %d · 카드 %d장' % (len(ROWS), len(cs)))
    open(SK, 'w', encoding='utf-8').write(out)
