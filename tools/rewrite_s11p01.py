PC = ['E1-119', 'E1-66', 'E1-60', 'E1-64', 'E1-65']


def close_brace(t, i):
    op = t[i]
    cl = {'{': '}', '[': ']'}[op]
    d, q, j = 0, None, i
    while j < len(t):
        c = t[j]
        if q:
            if c == '\\':
                j += 2
                continue
            if c == q:
                q = None
        elif c in '"\'`':
            q = c
        elif c == op:
            d += 1
        elif c == cl:
            d -= 1
            if d == 0:
                return j
        j += 1
    raise SystemExit('괄호 안 닫힘')


def q2(s):
    assert '"' not in s and '\\' not in s, s
    return '"%s"' % s


def main():
    src = open(SK, encoding='utf-8').read()
    i = src.index("{id:'s11p01'")
    e = close_brace(src, i)
    old = src[i:e + 1]

    # bx 는 그대로 옮긴다 — 기출 해설은 그림과 무관하게 유효하다.
    bx = old.split('bx:`', 1)[1]
    bx = bx[:bx.index('`')]
    # 다만 「오른쪽 받침대 위 기계」 같은 옛 그림 서술이 bx 안에 없는지 확인한다.
    for ghost in ['받침대']:
        assert ghost not in bx, 'bx 에 옛 그림 서술이 남아 있다: ' + ghost

    rows = []
    for prop, fact, cards in ROWS:
        r = '[' + q2(prop) + ',' + q2(fact)
        if cards:
            r += ',[' + ','.join(q2(c) for c in cards) + ']'
        rows.append(r + ']')

    new = ("{id:'s11p01',pc:[" + ','.join(q2(c) for c in PC) + "],t:'분기점',br:'" + BR
           + "',bx:`" + bx + "`,f:[" + ',\n  '.join(rows) + ']}')

    assert "'" not in BR, 'br 에 작은따옴표'
    out = src[:i] + new + src[e + 1:]

    # 되읽어 확인
    k = out.index("{id:'s11p01'")
    blk = out[k:close_brace(out, k) + 1]
    cards = re.findall(r'"(E1-[\w#]+)"', blk)
    assert len(cards) == len(set(cards)), '카드 중복: ' + str(cards)
    nrow = blk.split(',f:[', 1)[1].count('],[') + 1
    print('행 %d · 카드 %d장 %s' % (nrow, len(cards), ' '.join(cards)))
    print('블록 %d → %d bytes' % (len(old), len(new)))
    open(SK, 'w', encoding='utf-8').write(out)
    return 0


if __name__ == '__main__':
    sys.exit(main())
