    rows = []
    for prop, fact, cards in ROWS:
        r = '[' + q2(prop) + ',' + q2(fact)
        if cards:
            r += ',[' + ','.join(q2(c) for c in cards) + ']'
        rows.append(r + ']')

    assert "'" not in BR, 'br 에 작은따옴표'
    new = ("{id:'s11p02',pc:[" + ','.join(q2(c) for c in PC) + "],t:'중합효소 계보',br:'" + BR
           + "',bx:`" + bx + "`,f:[" + ',\n  '.join(rows) + ']}')
