    cards = re.findall(r'"([A-Z0-9]+[\w#-]*-[\w#]+)"', blk.split(',f:[', 1)[0]) \
        + re.findall(r'"([A-Z][\w#-]*-[\w#]+)"', blk.split(',f:[', 1)[1])
    assert len(cards) == len(set(cards)), '카드 중복: ' + str([c for c in cards if cards.count(c) > 1])
    print('행 %d · 카드 %d장' % (len(ROWS), len(cards)))
    print('  ' + ' '.join(cards))
    open(SK, 'w', encoding='utf-8').write(out)
    print('블록 %d → %d bytes' % (len(old), len(new)))
    return 0


