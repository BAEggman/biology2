    e = close_brace(src, i)
    old = src[i:e + 1]

    bx = old.split('bx:`', 1)[1]
    bx = bx[:bx.index('`')]
    for a, b in BX_FIX:
        n = bx.count(a)
        if n != 1:
            print('✗ bx 앵커 %d회: %s…' % (n, a[:50]))
            return 1
        bx = bx.replace(a, b)
    assert bx.count(BX_ADD_ANCHOR) == 1, 'qrule 앵커'
