def main():
    s = open(SK, encoding='utf-8').read()
    for old, new in EDITS:
        n = s.count(old)
        if n != 1:
            print('✗ 앵커가 %d회: %s…' % (n, old[:78]))
            return 1
        s = s.replace(old, new)

    i = s.index("{id:'s38p01'")
    d, q, k, esc = 0, None, i, False
    while k < len(s):
        c = s[k]
        if q:
            if esc: esc = False
            elif c == '\\': esc = True
            elif c == q: q = None
        elif c in '"\'`':
            q = c
        elif c == '{':
            d += 1
        elif c == '}':
            d -= 1
            if d == 0:
                break
        k += 1
    blk = s[i:k + 1]
    for gone in ['E1-30"', 'E1-30#1', 'E1-30#2', 'E1-33']:
        assert gone not in blk, '아직 %s 가 s38p01에 남아 있다' % gone
    cards = re.findall(r'"(E1-[\w#]+)"', blk)
    assert len(cards) == len(set(cards)), '카드 중복'
    assert '쇠못' not in blk and '구슬' not in blk, '쇠못·구슬이 남아 있다'
    open(SK, 'w', encoding='utf-8').write(s)
    print('s38p01 정정 완료 · 남은 카드 %d장 (E1-30 계열 4장은 d06p01로 이사)' % len(cards))
    return 0


if __name__ == '__main__':
    sys.exit(main())
