def close_brace(t, i):
    op = t[i]; cl = {'{': '}', '[': ']'}[op]
    d, q, j, esc = 0, None, i, False
    while j < len(t):
        c = t[j]
        if q:
            if esc: esc = False
            elif c == '\\': esc = True
            elif c == q: q = None
        elif c in '"\'`': q = c
        elif c == op: d += 1
        elif c == cl:
            d -= 1
            if d == 0: return j
        j += 1
    raise SystemExit('괄호 안 닫힘')


def q2(s):
    assert '"' not in s and '\\' not in s, s
    return '"%s"' % s


def main():
    src = open(SK, encoding='utf-8').read()
    assert "{id:'s17p03b'" not in src, '이미 있다'
    assert os.path.exists(os.path.join(ROOT, 'img', 's17p03b.webp')), '그림이 없다'

    # ① s17p03 pc 에서 H1-163 을 뺀다
    for pid, ids in PC_DROP.items():
        i = src.index("{id:'%s'" % pid)
        e = close_brace(src, i)
        blk = src[i:e + 1]
        for cid in ids:
            assert ',"%s"' % cid in blk, cid
            blk = blk.replace(',"%s"' % cid, '', 1)
            assert '"%s"' % cid not in blk, cid + ' 안 빠짐'
        src = src[:i] + blk + src[e + 1:]

    # ② s17p02 에 S-RN-11 을 행으로 건다 (배열)
    pid, needle, cards, extra = SIBLING
