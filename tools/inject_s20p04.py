    assert os.path.exists(os.path.join(ROOT, 'img', 's20p04.webp')), '그림이 없다'

    i = src.index("{id:'s20p03'")
    e = close_brace(src, i)
    rows = []
    for prop, fact, cards in ROWS:
        r = '[' + q2(prop) + ',' + q2(fact)
        if cards: r += ',[' + ','.join(q2(c) for c in cards) + ']'
        rows.append(r + ']')
    panel = ("{id:'s20p04',t:'어두운 쪽이 길어진다',br:'" + BR + "',bx:`" + BX + "`,f:["
             + ',\n     '.join(rows) + ']}')
    out = src[:e + 1] + ',\n   ' + panel + src[e + 1:]

    ids = re.findall(r"\{id:'([sd]\d+p\d+[ab-z]?)'", out)
    assert len(ids) == len(set(ids)), '패널 id 중복'
    b2 = out[out.index("{id:'s20p04'"):]
    b2 = b2[:close_brace(b2, 0) + 1]
    cs = re.findall(r'"([A-Z][A-Z0-9]*(?:-[A-Z0-9]+)*-[\w#]+)"', b2)
    assert len(cs) == len(set(cs)), '카드 중복: ' + str(cs)
    open(SK, 'w', encoding='utf-8').write(out)
    link_one(*SIBLING)
    print('s20p04 신설 · 행 %d · 카드 %d장 · s20p03 에 P1-20 배열' % (len(ROWS), len(cs)))
    return 0


