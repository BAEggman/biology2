#!/usr/bin/env python3
"""s11p05 · s11p01 — 짝짓개(suggest.js)가 찾아낸 다섯 장을 건다 (그림 무수정).

★ 손으로 훑던 것을 도구로 바꿨다. /tmp/mrg/suggest.js 가 미연결 카드와 기존 패널의
   낱말 겹침을 idf 가중으로 재서 「볼 값어치 있는 짝」만 추린다. 판정은 여전히
   그림을 보고 한다 — 점수 높은 것 중에도 그림에 없는 것이 섞여 있다.

  s11p05 「선로의 끝」 — 그림 확인: 세 선로, 오른쪽 끝 반복 판자가 5장 → 2장으로 줄고,
                       아래 선로에만 사람이 은빛 띠를 대고 판자를 얹는다
      #3 가운데 선로만 반복 판자가 줄었다   ← I1-41  말단 복제 문제의 정의
      #5 쇠 띠를 대고 그 위에 판자를 얹는다 ← I1-42  텔로머레이스의 작동
      #6 위·가운데 선로에는 아무도 없다     ← I1-43  활성인 세포 · F0-166 암세포 불멸성

  s11p01 「분기점」
      #8 이음매마다 튀는 용접 불꽃          ← C1-88  오카자키 절편을 잇는 효소

★ 걸지 않은 것 — 점수는 높았으나 그림에 없다
    C1-129 MCM 헬리케이스(G1에 원점에 붙어 S기 1회를 보장) — 「한 번만」을 막는 소품이 없다
    F0-44·45 RNA 중합효소가 푸는 범위 — s11p03과 낱말만 겹쳤다(수복 ≠ 전사)
    I1-21·23 PCR·Taq — 시험관 장면이 없다
"""
import os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SK = os.path.join(ROOT, 'sketchy.html')

EDITS = [
    # ── s11p05 #3 — 말단 복제 문제의 정의
    ('이 완충이 곧 「말단 보호」이고 「유전자 손실을 지연」이다",["C1-149"]]',
     '이 완충이 곧 「말단 보호」이고 「유전자 손실을 지연」이다. '
     '<b>선형 염색체라서</b> 생기는 문제이고, 짧아지는 쪽은 <b>3′ 말단</b>이다",'
     '["C1-149","I1-41"]]'),

    # ── s11p05 #5 — 텔로머레이스의 작동
    ('"<b>역전사</b> — RNA를 본으로 DNA를 만든다. '
     '그래서 텔로머레이스는 중합효소이면서 <b>역전사효소</b>다",["E1-120"]]',
     '"<b>역전사</b> — RNA를 본으로 DNA를 만든다. '
     '그래서 텔로머레이스는 중합효소이면서 <b>역전사효소</b>다. '
     '<b>자체 RNA 주형을 본떠 3′ 말단에 반복서열(척추동물 TTAGGG)을 새로 붙이는</b> 것이 '
     '이 한 동작이다 — 등에 진 쇠 띠가 주형, 얹는 나무 판자가 새 DNA다",'
     '["E1-120","I1-42"]]'),

    # ── s11p05 #6 — 활성인 세포 · 암세포 불멸성
    ('그래서 체세포는 분열 한계와 노화를 갖고, 암세포는 이 효소를 켜서 '
     '<b>제한 없이 분열</b>한다",["E1-95","E1-96","E1-97"]]',
     '그래서 체세포는 분열 한계와 노화를 갖고, 암세포는 이 효소를 켜서 '
     '<b>제한 없이 분열</b>한다. ★ 세 선로 중 <b>사람이 선 것이 하나뿐</b>인 것이 '
     '「대부분의 세포에서는 꺼져 있다」이고, 암세포의 <b>불멸성</b>이 이 사람을 '
     '도로 켠 결과다",["E1-95","E1-96","E1-97","I1-43","F0-166"]]'),

    # ── s11p01 #8 — 오카자키 절편을 잇는 효소
    ('오카자키 절편이 하나의 가닥이 되는 마무리는 두 걸음인데, 앞 걸음(쇠못을 나무못으로 '
     '바꾸기)은 다음 패널이고 <b>마지막 걸음이 이 용접</b>이다",'
     '["E1-74","E1-75","E1-63#3"]]',
     '오카자키 절편이 하나의 가닥이 되는 마무리는 두 걸음인데, 앞 걸음(쇠못을 나무못으로 '
     '바꾸기)은 다음 패널이고 <b>마지막 걸음이 이 용접</b>이다. '
     '조각들을 이어 붙이는 효소를 묻는 문제의 답은 언제나 <b>DNA 라이게이스</b>다",'
     '["E1-74","E1-75","E1-63#3","C1-88"]]'),
]


def main():
    s = open(SK, encoding='utf-8').read()
    for old, new in EDITS:
        n = s.count(old)
        if n != 1:
            print('✗ 앵커가 %d회: %s…' % (n, old[:70]))
            return 1
        s = s.replace(old, new)
    for pid in ('s11p05', 's11p01'):
        j = s.index("{id:'%s'" % pid)
        d, q, k, esc = 0, None, j, False
        while k < len(s):
            c = s[k]
            if q:
                if esc: esc = False
                elif c == '\\': esc = True
                elif c == q: q = None
            elif c in '"\'`': q = c
            elif c == '{': d += 1
            elif c == '}':
                d -= 1
                if d == 0: break
            k += 1
        cards = re.findall(r'"([A-Z]\d?-[\w#]+)"', s[j:k + 1])
        assert len(cards) == len(set(cards)), '%s 카드 중복' % pid
        print('%s 카드 %d장' % (pid, len(cards)))
    open(SK, 'w', encoding='utf-8').write(s)
    print('그림 무수정 다섯 장: I1-41 · I1-42 · I1-43 · F0-166 · C1-88')
    return 0


if __name__ == '__main__':
    sys.exit(main())
