def close_brace(t, i):
    op = t[i]
    cl = {'{': '}', '[': ']'}[op]
    d, q, j = 0, None, i
    while j < len(t):
        c = t[j]
        if q:
            if c == '\\':
                j += 2
                continue
            if c == q:
                q = None
        elif c in '"\'`':
            q = c
        elif c == op:
            d += 1
        elif c == cl:
            d -= 1
            if d == 0:
                return j
        j += 1
    raise SystemExit('괄호 안 닫힘')


def q2(s):
    assert '"' not in s and '\\' not in s, s
    return '"%s"' % s


def main():
    src = open(SK, encoding='utf-8').read()
    assert "{id:'s11p05'" not in src, '이미 있다'
    assert '`' not in BX, 'bx 에 백틱'
    assert "'" not in BR, 'br 에 작은따옴표'

    i = src.index("{id:'s11p04'")
    e = close_brace(src, i)

    rows = []
    for prop, fact, cards in ROWS:
        r = '[' + q2(prop) + ',' + q2(fact)
        if cards:
            r += ',[' + ','.join(q2(c) for c in cards) + ']'
        rows.append(r + ']')

    panel = ("{id:'s11p05',t:'선로의 끝',br:'" + BR + "',bx:`" + BX
             + "`,f:[" + ',\n  '.join(rows) + ']}')
    out = src[:e + 1] + ',\n  ' + panel + src[e + 1:]

    k = out.index("{id:'s11p05'")
    blk = out[k:close_brace(out, k) + 1]
    ids = re.findall(r"\{id:'([sd]\d+p\d+[ab]?)'", out)
    assert len(ids) == len(set(ids)), '패널 id 중복'
    assert ids.index('s11p05') == ids.index('s11p04') + 1, '위치 오류'
    cards = re.findall(r'"([A-Z]\d?-\d+)"', blk)
    assert len(cards) == len(set(cards)), '카드 중복'
    print('패널 %d개 · s11p05 행 %d · 카드 %d장 %s' % (len(ids), len(ROWS), len(cards), ' '.join(cards)))
    open(SK, 'w', encoding='utf-8').write(out)
    return 0


if __name__ == '__main__':
    sys.exit(main())
