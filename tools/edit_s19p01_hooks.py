#!/usr/bin/env python3
"""s19p01 「두 관문」 — 음성 후크판으로 교체.

★ 무엇이 바뀌나
  그림이 관계만 가르치고 이름을 하나도 안 날랐다. 새 그림은 이름을 나른다:
    Rb=루비(루비듐 원소기호) · E2F=숫자 2와 F자 장대 · MPF=앰프 ·
    Cdk1=음반 한 장 · 사이클린 B=자전거 · Cdc25=음반 여러 장
  Wee1(위원장 어깨띠)만 그림에 안 나왔다 — 걸지 않고 다음 편집으로 미룬다.

★ 그린 것만 건다 — 패널 카드 6장을 뗀다
  C1-0(주기 4단계) · C1-68(DNA 2배) · C1-91(난할) — 그림에 없다
  C1-83(개구리 난모세포 실험) · C1-84(사이클린 B 유비퀴틴화 파괴) — 장면이 없다
  C1-137(Cyclin E + Cdk2) — E도 2도 이 그림에서 E2F를 뜻한다. 오히려 오독을 만든다
"""
import re, sys, subprocess

SK = '/tmp/b2/sketchy.html'
src = open(SK, encoding='utf-8').read()

i = src.index("{id:'s19p01'")
d, q, k, esc = 0, None, i, False
while k < len(src):
    c = src[k]
    if q:
        if esc: esc = False
        elif c == '\\': esc = True
        elif c == q: q = None
    elif c in '"\'`': q = c
    elif c == '{': d += 1
    elif c == '}':
        d -= 1
        if d == 0: break
    k += 1
j = k + 1
blk = src[i:j]

# bx는 그대로 두고 후크 문단만 덧붙인다
bx = blk[blk.index(',bx:`')+5 : blk.index('`,f:[')]
bx += ("<p><b>★ 이름은 소품이 나른다.</b> 이 단원의 이름은 전부 <b>임의 라벨</b>이라 "
       "논리로 따라갈 수가 없다. 그래서 소리로 잡는다 — <b>루비</b>가 Rb(원소기호로 루비듐이다), "
       "조끼의 <b>2</b>와 <b>F자 장대</b>가 E2F, 바닥의 <b>앰프</b>가 MPF(엠피에프), "
       "레버의 <b>음반 한 장</b>이 Cdk1(CD+1), 옆에 선 <b>자전거</b>가 사이클린 B(사이클), "
       "자물쇠를 끊는 사람이 든 <b>음반 여러 장</b>이 Cdc25다. "
       "그림을 떠올리면 이름이 같이 따라 나오게 만든 것이지, 루비가 Rb 단백질과 무슨 관계가 있어서가 아니다 — "
       "후크는 <b>인출 단서</b>이지 사실이 아니다.</p>"
       "<p><b>아직 안 된 것.</b> Wee1은 「위원장 어깨띠」로 잡으려 했는데 그림에 안 나왔다. "
       "그래서 <b>걸지 않았다</b> — 다음 편집에서 어깨띠를 넣는다.</p>")

ROWS = [
 ('아치 앞 — 가슴에 머리만 한 <b>붉은 루비</b>를 건 덩치가 주자의 멱살을 붙잡아 못 가게 한다',
  '<b>Rb</b>가 <b>E2F</b>를 붙들고 있어 S기가 꺼져 있다. ★ <b>루비가 곧 이름이다</b> — '
  'Rb는 원소기호로 루비듐이라 소리가 그대로 붙는다', ['C1-20']),
 ('붙잡힌 주자 — 조끼 앞을 채운 큰 <b>숫자 2</b>, 손에 끝이 <b>F자로 꺾인</b> 장대',
  '<b>E2F</b> — 숫자 <b>2</b>와 <b>F</b>자가 곧 이름이다. Rb가 놓아 주면 S기 유전자를 켜는 전사인자',
  ['C1-21']),
 ('덩치의 어깨에 찍힌 붉은 <b>도장</b> 자국 · 허리춤에 꽂힌 도장',
  'Rb가 <b>인산화</b>되면 E2F를 놓아 준다 — 미는 것이 아니라 <b>놓는 것</b>이다. '
  'G1-Cdk가 가장 먼저 표적으로 삼아 무력화시키는 것이 Rb다', ['C1-140']),
 ('두 손을 활짝 펴자 주자가 아치를 빠져나가 달린다',
  '여기가 <b>G1 검문소(제한점, restriction point)</b>다 — 세포주기에서 가장 중요한 검문소이고, '
  '한 번 지나면 되돌리지 않는다', ['C1-19']),
 ('금고문 앞 바닥의 <b>앰프</b> 상자 — 그 위에서 나온 긴 쇠 레버가 문을 가로질러 잠그고 있다',
  '<b>MPF</b> — 엠피에프가 곧 <b>앰프</b>다. 이 레버가 내려가야 M기로 들어간다', ['C1-81']),
 ('레버에 끼운 <b>음반 한 장</b>과 문 옆에 세워 둔 <b>자전거</b>',
  'MPF의 정체는 <b>사이클린 B + Cdk1</b>이다 — <b>자전거(사이클)</b>가 사이클린 B, '
  '<b>음반(CD) 한 장</b>이 Cdk1이다. Cdk는 사이클린과 <b>결합해야만</b> 활성이 생기고, '
  '이름부터가 <b>사이클린 의존성</b> 인산화효소다', ['C1-139', 'C1-18', 'C1-17']),
 ('레버에 <b>검은 쇠 자물쇠</b>를 채우는 사람',
  '<b>Wee1</b>의 억제성 인산화 — M기 진입 전에 MPF를 붙들어 둔다. '
  '★ 자물쇠가 <b>검은 쇠</b>인 것은 덱에서 <b>금색 자물쇠가 약물·독물 전용</b>이기 때문이다',
  ['C1-127']),
 ('<b>음반을 여러 장 부채처럼 쥔</b> 사람이 그 날로 자물쇠를 끊는다 · 자물쇠가 두 동강 나 바닥에 떨어졌다',
  '<b>Cdc25</b>가 억제성 인산기를 <b>떼어내</b> 폭발적으로 활성화한다 (G2/M). '
  'Cdk1과 <b>같은 Cd- 계열</b>이라 음반을 나눠 쓴다 — 다만 Cdk1은 <b>한 장</b>, Cdc25는 <b>여러 장</b>이다',
  ['C1-128']),
 ('자물쇠가 끊기자 레버가 끝까지 내려가고 금고문이 활짝 열렸다',
  '두 관문의 문법이 같다 — <b>붙잡던 것이 풀리는 순간</b>이 통과 시점이지 '
  '새로 미는 힘이 생기는 것이 아니다', []),
]

BR = ('두 관문 모두 <b>붙잡던 것이 풀리는 순간</b>이 통과 시점이다. '
      '첫째는 도장이 찍히자 손이 풀리고, 둘째는 자물쇠가 끊기자 레버가 내려간다. '
      '★ 이름은 소품이 나른다 — <b>루비</b>가 Rb, <b>2와 F</b>가 E2F, <b>앰프</b>가 MPF, '
      '<b>음반 한 장</b>이 Cdk1, <b>자전거</b>가 사이클린 B다.')

def q2(s):
    assert '"' not in s and '\\' not in s, s
    return '"%s"' % s

rows = []
for prop, fact, cards in ROWS:
    r = '[' + q2(prop) + ',' + q2(fact)
    if cards: r += ',[' + ','.join(q2(c) for c in cards) + ']'
    rows.append(r + ']')

assert "'" not in BR and '`' not in bx
new = ("{id:'s19p01',t:'두 관문',br:'" + BR + "',bx:`" + bx + "`,f:["
       + ',\n     '.join(rows) + ']}')

out = src[:i] + new + src[j:]
ids = re.findall(r'"([A-Z][A-Z0-9]*(?:-[A-Z0-9]+)*-[\w#]+)"', new)
assert len(ids) == len(set(ids)), '카드 중복'
open(SK, 'w', encoding='utf-8').write(out)
print('s19p01 교체 · 행 %d · 카드 %d장 (%s)' % (len(ROWS), len(ids), ' '.join(sorted(ids))))
