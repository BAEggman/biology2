# -*- coding: utf-8 -*-
"""s17p04 4행 정정 — 그리지 않은 이름은 부르지 않는다.

이 판(우물 셋)은 헨레고리를 이름으로 부르지만 그 이름을 나르는 소품이 없다.
그런데 **그 고리는 이 판에 이미 그려져 있다** — 2행의 「옆구리 기계가 흰 알갱이를 벽에
뿌린다」가 굵은 상행각이고, 그것이 수질 기울기를 만드는 바로 그 단계다.

그러니 이름을 부르는 대신 **그림에 있는 것**을 가리킨다.
이름은 앞 판 s17p02 의 제목(「헨레고리」)이 나른다.
"""
import os
SK = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'sketchy.html')
s = open(SK, encoding='utf-8').read()
# ⚠ 같은 문장이 bx 산문에도 있다. bx 는 감사 대상이 아니고 거기서는 이름을 불러도 된다
#    (학생이 읽는 글이다) — 사실 칸 쪽만 고르려고 앞 문장을 붙여 바늘을 늘렸다.
OLD = '수질 기울기는 존재한다</b>. 기울기를 만드는 것은 ADH가 아니라 헨레고리다'
NEW = ('수질 기울기는 존재한다</b>. 기울기를 만드는 것은 ADH가 아니라 '
       '<b>옆구리 기계</b>(굵은 상행각)다 — 이 판 둘째 줄에 이미 그려져 있고, '
       '그 고리의 이름은 앞 판 제목에 있다')
assert s.count(OLD) == 1, s.count(OLD)
open(SK, 'w', encoding='utf-8').write(s.replace(OLD, NEW, 1))
print('s17p04 4행 — 헨레고리 → 옆구리 기계(굵은 상행각)')
