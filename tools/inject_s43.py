    out = src[:e + 1] + ',\n ' + scene + src[e + 1:]

    ids = re.findall(r"\{id:'([sd]\d+p\d+[ab]?)'", out)
    assert len(ids) == len(set(ids)), '패널 id 중복'
    blk = out[out.index("{id:'s43p01'"):]
    blk = blk[:close_brace(blk, 0) + 1]
    cards = re.findall(r'"([A-Z][A-Z0-9]*(?:-[A-Z0-9]+)*-[\w#]+)"', blk)
    assert len(cards) == len(set(cards)), '카드 중복'
